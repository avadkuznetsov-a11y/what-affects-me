# и вспоминает их вслух, «вчера пил вино», «в среду был перелёт». Такую запись
# надо положить в ТОТ день, иначе она перепутает всю статистику.

_YESTERDAY = {"вчера": 1, "позавчера": 2}

# Дни недели: имя и номер, как их считает date.weekday() - понедельник ноль.
_WEEKDAYS: list[tuple[str, int]] = [
    (r"понедельник\w*", 0),
    (r"вторник\w*", 1),
    (r"сред[уыа]\b", 2),
    (r"четверг\w*", 3),
    (r"пятниц[уые]\b", 4),
    (r"суббот[уыа]\b", 5),
    (r"воскресень[еяю]\b", 6),
]

# Внутри скольких слов от начала фразы день считается её темой. Дальше это уже
# не «про какой день рассказ», а пояснение внутри рассказа про сегодня:
# «на 7, но это скорее из-за того что вчера лёг рано» - оценка за сегодня, и
# уводить её во вчера нельзя.
DAY_WORDS = 2

# Дальше недели назад по названию дня недели не уходим: «в среду» через две
# недели человек имеет в виду редко, а ошибка тут дорогая - факт ляжет не в
# тот день и в статистике останется навсегда.
_WEEK = 7


def day_mentioned(text: str, today: date, anywhere: bool = False) -> date | None:
    """
    Про какой прошедший день говорит фраза. None - про сегодня или непонятно.

    Смотрим только начало фразы: так люди и говорят, когда рассказывают про
    другой день. Про сегодняшний день ничего не возвращаем - он и так текущий.

    anywhere - искать день по всей фразе. Нужно для поправок: «а нет, вру, это
    был вторник» называет день в конце, и по первым словам его не найти.
    """
    lowered = text.strip().lower()
    if not lowered:
        return None
    # Граница «первых двух слов» в символах: считать слова по отдельности
    # незачем, нам нужно ровно одно - началась ли фраза с названия дня.
    words = re.split(r"\s+", lowered)[:DAY_WORDS]
    head = lowered if anywhere else " ".join(words)

    for word, back in _YESTERDAY.items():
        if re.search(rf"\b{word}\b", head):
            return today - timedelta(days=back)

    for pattern, weekday in _WEEKDAYS:
        if not re.search(pattern, head):
            continue
        back = (today.weekday() - weekday) % _WEEK
        # «В среду», сказанное в среду, - это про сегодня: своим же днём
        # недели человек называет прошлую неделю крайне редко.
        return None if back == 0 else today - timedelta(days=back)

    return None


class Extractor(Protocol):
    """Любой разборщик рассказа — правила или модель."""

    def extract(self, text: str, day: date, context: str = "") -> DayRecord: ...


class RuleExtractor:
    """Разбор по правилам: быстрый, бесплатный, полностью офлайн."""

    def extract(self, text: str, day: date, context: str = "") -> DayRecord:
        """Контекст правилам не нужен: словарь смотрит только саму фразу."""
        record = DayRecord(day=day, raw_text=text)
        lowered = text.lower()

        for pattern, name in _FACTOR_PATTERNS:
            match = re.search(pattern, lowered)
            if not match:
                continue
            # «не пил кофе» — это факт об отсутствии фактора, а не о его наличии.
            # Отрицание бывает и справа: «сладкого не было», «кофе не пил» -
            # так говорят не реже, а разбор видел только левую сторону и
            # записывал привычку как случившуюся.
            window = lowered[max(0, match.start() - 20):match.start()]
            after = lowered[match.end():match.end() + 25]
            value = 0.0 if (_NEGATION.search(window)
                            or _NEGATION_AFTER.search(after)) else 1.0
            around = _around(text, match.start())
            record.add(Fact("factor", name, value, "diary", quote=around))
            # Время кладём ОТДЕЛЬНЫМ фактором, а не вместо обычного: иначе
            # «кофе» распадётся на утренний и вечерний, и ни один не наберёт
            # дней. Так у общего фактора статистика цела, а у «кофе вечером»
            # своя - и видно, что мешает спать именно вечерний.
            when = timed_name(name, part_of_day(clause_around(text, match.start())
                                                or around or text))
            if when and value > 0:
                record.add(Fact("factor", when, value, "diary", quote=around))

        for pattern, name in _METRIC_PATTERNS:
            match = re.search(pattern, lowered)
            if not match:
                continue
            score = _score_near(lowered, match.start(), metric=name)
            if score is None:
                score = _NEGATIVE_BY_DEFAULT.get(name)
            if score is not None:
                record.add(Fact("metric", name, score, "diary", quote=_around(text, match.start())))

        return record


class LLMExtractor:
    """
    Разбор моделью. Модель отвечает строгим JSON — свободный текст в ответе
    не принимается, иначе факты невозможно свести к общим именам.
    """

    # Список показателей закрытый: если модель придумает своё название,
    # связи по нему никогда не наберут статистики.
    METRICS = ("качество сна", "энергия", "тревога", "настроение", "головная боль")

    PROMPT = (
        "Ты разбираешь дневниковую запись человека. Верни СТРОГО JSON вида\n"
        '{"factors": [{"name": "...", "value": 1}], '
        '"metrics": [{"name": "...", "value": 7}], "events": ["..."]}\n'
        "Правила:\n"
        "1. factors - что человек делал или что с ним случилось. Имя короткое, в именительном "
        "падеже: «кофе», «тренировка», «перелёт», «работа», «ссора с руководителем». value: 1 "
        "если было, 0 если человек прямо говорит, что этого не было. Записывай КАЖДОЕ занятие, "
        "которое назвал человек, даже если в одной фразе их несколько.\n"
        "1а. Если у привычки названо время суток и она из списка «кофе, алкоголь, "
        "тренировка, прогулка» - добавь ВТОРОЙ факт с временем: «кофе» и «кофе вечером», "
        "«тренировка» и «тренировка утром». Слова только такие: утром, днём, вечером, "
        "ночью. Времени не сказано - второго факта нет.\n"
        "2. Одинаковые по смыслу формулировки своди к одному имени. Если привычка есть в "
        "списке ниже, бери имя ОТТУДА - слово в слово. Своё имя придумывай только для того, "
        "чего в списке нет («ссора с тёщей», «переезд»).\n"
        "   Список имён: " + ", ".join(name for _, name in _FACTOR_PATTERNS) + ".\n"
        "   Примеры сведения: «пробежка», «зал», «йога», «плавал» - «тренировка»; "
        "«лёг в три», «допоздна не спал» - «поздний отбой»; «вино», «пиво», «виски» - "
        "«алкоголь»; «созвон», «совещание» - «много встреч»; «дедлайн», «завал» - «аврал».\n"
        "2б. «Поздний отбой» ставь, только если человек сказал, что лёг поздно или "
        "во сколько лёг. «Не мог уснуть», «ворочался», «долго засыпал» - это не "
        "поздний отбой, а качество сна: он лёг вовремя, но не спал.\n"
        "2в. «Тяжёлое событие» - только про горе и потерю: смерть близкого, "
        "похороны, развод, увольнение, больница, авария. Простуда и болезнь - "
        "это «болезнь», ссора - это «ссора».\n"
        "2а. Еда - такой же фактор, как всё остальное, и её надо записывать. Своди её к "
        "этим именам: мясо, рыба, овощи, фастфуд, сладкое, выпечка, молочное, острое, "
        "поздний ужин, переедание, пропустил обед. «Ел много мяса» - «мясо»; «бургер», "
        "«пицца», «шаурма» - «фастфуд»; «наелся на ночь» - «поздний ужин»; «объелся» - "
        "«переедание»; «весь день на кофе», «забыл поесть» - «пропустил обед» (и «кофе», "
        "если кофе назван). Оценок еде не даём: полезная она или вредная - не наше дело.\n"
        "3. metrics - только из этого списка: качество сна, энергия, тревога, настроение, "
        "головная боль. Другие названия не придумывай.\n"
        "4. value у metrics - ЦЕЛОЕ число от 0 до 10, где 10 - отлично, 0 - хуже некуда. "
        "Это относится и к тревоге: сильная тревога это 2, спокойный день это 9. "
        "Восемь часов сна это 10, четыре часа это 5.\n"
        "5. Про самочувствие люди говорят обиняками, и это тоже оценка: «вымотался», "
        "«хотелось спать», «еле дожил до вечера» - энергия 2; «всё валится из рук», «грустно» - "
        "настроение 3; «места себе не находил» - тревога 2; «выспался», «бодрый» - энергия 8. "
        "Понимай такие слова, а не жди готовых оценок в баллах.\n"
        "6. Ничего не выдумывай: чего в записи нет, того нет в ответе. Но и не молчи там, "
        "где смысл понятен из обычной речи.\n"
        "\n"
        "Примеры разбора:\n"
        "Запись: выпил кофе в шесть вечера\n"
        '{"factors": [{"name": "кофе", "value": 1}, {"name": "кофе вечером", "value": 1}], '
        '"metrics": [], "events": []}\n'
        "Запись: гулял, пил вино, работал\n"
        '{"factors": [{"name": "прогулка", "value": 1}, {"name": "алкоголь", "value": 1}, '
        '{"name": "работа", "value": 1}], "metrics": [], "events": []}\n'
        "Запись: ел много мяса и фастфуд, к вечеру разбитый\n"
        '{"factors": [{"name": "мясо", "value": 1}, {"name": "фастфуд", "value": 1}], '
        '"metrics": [{"name": "энергия", "value": 3}], "events": []}\n'
        "Запись: очень тяжело, хотелось спать\n"
        '{"factors": [], "metrics": [{"name": "энергия", "value": 2}], "events": []}\n'
        "Запись: с утра поцапался с тёщей, весь день как выжатый лимон, ночью ворочался\n"
        '{"factors": [{"name": "ссора с тёщей", "value": 1}], '
        '"metrics": [{"name": "энергия", "value": 2}, {"name": "качество сна", "value": 4}], '
        '"events": []}\n'
        "\n"
        "Запись:\n"
    )

    def __init__(self, complete) -> None:
        """complete(prompt: str) -> str — любой вызов модели, возвращающий текст."""
        self._complete = complete

    # Предыдущая реплика разговора. Без неё поправки не разбираются вовсе:
    # «нет, вру, одну чашку утром всё-таки выпил» само по себе не про кофе -
    # про кофе была фраза до него. Модель видит контекст, но разбирает ТОЛЬКО
    # новую фразу, иначе вчерашние привычки записывались бы заново каждый раз.
    CONTEXT_HEAD = (
        "НАЧАЛО КОНТЕКСТА. Это уже сказано раньше и УЖЕ ЗАПИСАНО. Разбирать "
        "его нельзя: он нужен только чтобы понять поправку или короткий ответ "
        "в новой записи («нет, вру, одну всё-таки выпил» - про то, о чём "
        "говорили до этого). Ничего отсюда в ответ не переноси.\n"
    )
    CONTEXT_TAIL = (
        "\nКОНЕЦ КОНТЕКСТА. Дальше - новая запись, разбирать надо ТОЛЬКО её.\n\n"
    )

    def extract(self, text: str, day: date, context: str = "") -> DayRecord:
        record = DayRecord(day=day, raw_text=text)
        prompt = self.PROMPT
        if context.strip():
            prompt = self.CONTEXT_HEAD + context.strip() + self.CONTEXT_TAIL + prompt
        raw = self._complete(prompt + text)
        data = _parse_json(raw)
        for item in data.get("factors", []):
            name = str(item.get("name", "")).strip().lower()
            # «сон» - это то, что измеряют, а не то, что делают. Модель иногда
            # кладёт показатель в привычки; такие записи только мусорят список.
            if not name or _canonical_metric(name):
                continue
            record.add(Fact("factor", canonical_factor(name),
                            float(item.get("value", 1)), "diary"))
        lowered = text.lower()
        for item in data.get("metrics", []):
            name = _canonical_metric(str(item.get("name", "")).strip().lower())
            if not name:
                continue        # показатель не из нашего списка - в статистику не годится
            value = float(item.get("value", 0))
            # Модель любит дописать нули по всем показателям сразу. Ноль без
            # единого слова об этом в тексте - выдумка, а не наблюдение.
            # А вот ненулевую оценку принимаем: модель прочитала фразу целиком
            # и понимает «весело» или «выжат» лучше любого словаря.
            if value == 0 and not _mentioned(name, lowered):
                continue
            record.add(Fact("metric", name, value, "diary"))
        for name in data.get("events", []):
            record.add(Fact("event", str(name).strip().lower(), 1.0, "diary"))
        return record


_METRIC_ALIASES = {
    "сон": "качество сна", "качество сна": "качество сна", "сонливость": "качество сна",
    "энергия": "энергия", "силы": "энергия", "бодрость": "энергия", "усталость": "энергия",
    "тревога": "тревога", "тревожность": "тревога", "беспокойство": "тревога",
    "настроение": "настроение", "самочувствие": "настроение",
    "головная боль": "головная боль", "голова": "головная боль", "мигрень": "головная боль",
}


def _mentioned(metric: str, lowered: str) -> bool:
    """Есть ли в тексте хоть какой-то намёк на этот показатель."""
    for pattern, name in _METRIC_PATTERNS:
        if name == metric and re.search(pattern, lowered):
            return True
    return False


def _canonical_metric(name: str) -> str:
    """Модель называет показатели по-разному - сводим к общему словарю."""
    return _METRIC_ALIASES.get(name, "")


def _around(text: str, index: int, width: int = 40) -> str:
    start = max(0, index - width // 2)
    return text[start:start + width].strip()


# Знаки, по которым фраза делится на отдельные мысли: «утром кофе, вечером
# пиво» - это два разных времени, и путать их нельзя.
_CLAUSE_BREAK = re.compile(r"[,;.!?]|\bа потом\b|\bи потом\b")


def clause_around(text: str, index: int) -> str:
    """
    Кусок фразы, в котором стоит слово: от ближайшей запятой слева до
    ближайшей справа.

    Время суток искали в окне из сорока символов вокруг привычки, и «вечером
    выпил с друзьями пива» время теряло: до «пива» сорок символов уже не
    доставали до «вечером», а обрезок «ром» ничего не значит. По мысли целиком
    время находится, но «утром кофе, вечером тренировка» при этом не
    перемешивается - разные мысли разделены запятой.
    """
    left = 0
    for found in _CLAUSE_BREAK.finditer(text, 0, index):
        left = found.end()
    right = _CLAUSE_BREAK.search(text, index)
    return text[left:right.start() if right else len(text)].strip()


def _score_near(lowered: str, index: int, window: int = 60, metric: str = "") -> float | None:
    """Оценка состояния рядом с упоминанием: цифрой («сон на 3») или словом."""
    fragment = lowered[max(0, index - window):index + window]

    digits = re.search(r"\b(10|[0-9])\s*(?:/\s*10|из\s*10|балл)", fragment)
    if digits:
        return float(digits.group(1))

    # «спал 5 часов», «часов пять поспал» — это мера сна и только его:
    # рядом стоящая «тревога» не должна получить оценку из часов
    if metric != "качество сна":
        return _word_score(fragment)

    hours = re.search(r"(\d{1,2})\s*час", fragment) or re.search(r"час\w*\s+(\d{1,2})\b", fragment)
    if hours:
        return min(10.0, round(float(hours.group(1)) / 8 * 10, 1))

    # Рядом со словом «час» может оказаться и глагол («спал часов»), поэтому
    # смотрим слова и справа, и слева, и берём первое, которое правда число.
    for pattern in (r"час\w*\s+(\w+)", r"(\w+)\s+час"):
        for match in re.finditer(pattern, fragment):
            number = _WORD_NUMBERS.get(match.group(1))
            if number:
                return min(10.0, round(number / 8 * 10, 1))

    return _word_score(fragment)


def measured_number(text: str) -> bool:
    """
    Мера ли то число, которое в ответе примут за оценку: «5 часов», «8 встреч»,
    «спал часов пять», «выпил 2 кофе».

    Смотрим ровно одно число - первое, которое возьмёт `apply_answer`, - и по
    одному слову с каждой стороны от него. Слова слева не смотрели вовсе, и
    «спал часов пять» в ответ на вопрос про тревогу становилось тревогой на
    пятёрку. Перебирать все числа нельзя - любая мера в конце реплики съедала
    бы названную в начале оценку: «на 8, бегал 5 км» это оценка.
    """
    lowered = text.lower()
    match = SCORE_NUMBER.search(lowered) or _ANY_WORD_NUMBER.search(lowered)
    if match is None:
        return False
    # Мера стоит вплотную к своему числу; запятая между ними - это уже
    # отдельная мысль: «на 8, бегал 5 км».
    after = re.match(r"\s*([а-яёa-z]+)", lowered[match.end():])
    before = re.search(r"([а-яёa-z]+)\s*$", lowered[:match.start()])
    return any(_is_measure(word.group(1)) for word in (after, before) if word)


def _is_measure(word: str) -> bool:
    """Мера или счётное слово при числе: «часов», «встреч», «кофе», «пива»."""
    return bool(_UNIT.fullmatch(word) or _COUNTED.search(word))


def _word_score(fragment: str) -> float | None:
    """Оценка словами: «ужасно», «нормально», «отлично»."""
    for pattern, score in _WORD_SCORES:
        if re.search(pattern, fragment):
            return score
    return None


def _parse_json(raw: str) -> dict:
    """Модель иногда оборачивает JSON в пояснения — достаём первый объект."""
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", raw, re.DOTALL)
        if not match:
            return {}
        try:
            return json.loads(match.group(0))
        except json.JSONDecodeError:
            return {}
