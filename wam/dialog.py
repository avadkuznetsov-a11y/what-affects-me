# Сколько уточнений за день. Вопрос - это не анкета, а способ разобраться: без
# «сколько выпили» и «долго ли гуляли» связь получается грубой. Ограничение
# всё же есть: подряд на одну реплику мы задаём ровно один вопрос, повторно
# один и тот же не задаём никогда, и на день их всё-таки не десяток.
MAX_QUESTIONS = 6

# Длиннее этого реплика - уже рассказ про день, а не оценка в ответ на вопрос.
MAX_ANSWER_WORDS = 8

# Пока дней в дневнике меньше, про отсутствие выводов лучше молчать: сказать
# «данных мало» человеку, который ведёт дневник второй день, - значит повторять
# очевидное на каждую фразу.
MIN_DAYS_FOR_HINT = 7

# Приветствие и благодарность - не рассказ про день, но и не белиберда.
# Отвечать на «привет» подсказкой «не понял, что записать» - самый быстрый
# способ показать человеку, что перед ним не собеседник, а форма ввода.
_GREETING = re.compile(r"(привет\w*|здравствуй\w*|здрасьте|доброго\s+\w+|"
                       r"добр(?:ое|ый|ой)\s+(?:утр\w+|день|вечер|ноч\w+)|"
                       r"хай|ку|салют|доброй\s+ночи)\b")
_THANKS = re.compile(r"(спасибо|спс|благодар\w*|пасиб\w*)\b")

GREETING_REPLY = ("Здравствуйте. Расскажите, как прошёл день - что делали и как "
                  "себя чувствовали.")
THANKS_REPLY = "Пожалуйста. Будет что записать - пишите."

# Короткий отказ на случай, когда вопрос уже висит: повторять его слово в слово
# нельзя, а молчать в ответ на непонятую фразу - невежливо.
DID_NOT_GET_IT = "Не понял. Скажите обычными словами, что было и как вы себя чувствовали."

# Человек повторил то, что уже в дневнике. Отвечать ему «не понял» - неправда:
# понял, просто нового ничего нет.
ALREADY_KNOWN = "Это у меня уже записано. Если что-то было ещё - расскажите."

# «А как вы себя чувствовали?» спрашивает не про конкретный показатель, поэтому
# голая оценка к нему не привязывается: семь - это про что?
def which_metric(said: str = "") -> str:
    """
    «Семь - это про что?» Число берём из самой реплики: спрашивать про семь,
    когда человек сказал «на четыре», - значит показать, что его не читали.
    """
    number = SCORE_NUMBER.search(said.lower())
    named = number.group(1) if number else ""
    if not named:
        for word, value in _WORD_NUMBERS.items():
            if value <= 10 and re.search(rf"\b{word}\b", said.lower()):
                named = str(value)
                break
    head = f"{named} - это про что" if named else "Это про что"
    return (f"{head}: сон, тревога, силы, настроение? "
            "Можно и словами: «выспался», «разбитый», «спокойный день».")


# Тот же текст без реплики - для тестов и для показа в документации.
WHICH_METRIC = which_metric()

# Хвост этого вопроса - по нему узнаём его в ленте, какое бы число ни стояло
# в начале.
WHICH_METRIC_TAIL = "«выспался», «разбитый», «спокойный день»."


def _score_said(text: str) -> float | None:
    """Число из реплики: «на 4», «четыре». None - числа нет."""
    number = SCORE_NUMBER.search(text)
    if number:
        return float(number.group(1))
    for word, value in _WORD_NUMBERS.items():
        if value <= 10 and re.search(rf"\b{word}\b", text):
            return float(value)
    return None

# Оценка, названная словом: «пятёрку», «восемь». Список тот же, по которому
# ответы разбирает `questions.score_in` - двух списков тут быть не должно.
_SCORE_WORDS = tuple(word for word, value in _WORD_NUMBERS.items() if value <= 10)


# Оценка без единого слова про самочувствие: «7», «на 7», «баллов 7», а ещё
# «где-то на пятёрку» и «на троечку» - так говорят не реже, чем цифрой.
_BARE_SCORE = re.compile(
    r"^(?:где-?то\s+|примерно\s+|наверное\s+|ну\s+)?"
    r"(?:на\s+|баллов\s+)?"
    r"(?:10|\d|" + "|".join(_SCORE_WORDS) + r")"
    r"(?:\s*(?:из\s*10|балл\w*))?[.!]?$")


# Оценка внутри фразы: «на 7, но вчера лёг рано». Разобрать такую целиком мы
# не смогли, но и «не понял» тут неправда: число человек назвал, непонятно
# только, про что оно.
_SCORE_PHRASE = re.compile(r"\bна\s+(?:10|\d)\b")


def _bare_score(text: str) -> bool:
    return bool(_BARE_SCORE.match(text.strip()))


# Ответ на вопрос о детали - короткая реплика вроде «две чашки, последняя в
# пять» или «часа полтора». Длинный рассказ деталью не считаем: человек просто
# продолжил про день, и разбирать это надо обычным путём.
MAX_DETAIL_WORDS = 12


def _polite(text: str) -> bool:
    """
    Вежливость: человек поздоровался или поблагодарил, а не пытался ответить.

    Отговорки («ну не знаю», «ладно») сюда НЕ входят: это отказ отвечать, и
    вопрос от них должен гаснуть - иначе бот превращается в зануду.
    """
    lowered = text.strip().lower()
    return bool(_GREETING.match(lowered) or _THANKS.match(lowered))


# Мера в ответе про привычку: число, слово-число или прямая оценка количества.
# Без этого деталью считалась любая короткая реплика - и «меня не было неделю,
# сейчас расскажу» записывалось уточнением к прогулке.
_MEASURE_WORDS = re.compile(
    r"\d|"
    r"\b(?:один|одну|одна|два|две|три|четыре|пять|шесть|семь|восемь|"
    r"девять|десять|полтора|полчаса|чуть|немного|"
    r"пара|пары|пару|несколько|почти|совсем|"
    r"минут\w*|часа?\w*|чашк\w*|бокал\w*|стакан\w*|литр\w*|раз\w*|"
    r"штук\w*|км|килом\w*|шаг\w*|бутыл\w*|кружк\w*|порци\w*)\b|"
    r"\b(?:утром|днём|днем|вечером|ночью|после|перед|до|в обед)\b")


def _looks_like_detail(text: str) -> bool:
    lowered = text.strip().lower()
    if not lowered or len(lowered.split()) > MAX_DETAIL_WORDS:
        return False
    # Приветствие и благодарность - это вежливость, а не ответ на вопрос.
    # Пока их принимали за деталь, «привет» после вопроса про кофе записывался
    # как уточнение к кофе, и человек видел «Записал: кофе» на своё «привет».
    if _GREETING.match(lowered) or _THANKS.match(lowered):
        return False
    # Как и невнятное «ага», «ну не знаю» - согласие, а не мера
    if _VAGUE.match(lowered):
        return False
    # Спрашивали про меру - значит в ответе должна быть мера. Иначе человек
    # просто продолжил рассказ, и разбирать его надо обычным путём.
    return bool(_MEASURE_WORDS.search(lowered))


# Реплики, которые ничего не сообщают: человек тянет время или просто
# откликается. Деталью привычки они быть не могут.
_VAGUE = re.compile(r"^(ага|угу|ок(ей)?|да|нет|не знаю|ну не знаю|"
                    r"наверное|потом|ладно|понял\w*|хорошо)\b")


def _remember_detail(record: DayRecord, factor: str, text: str) -> Fact | None:
    """
    Дописать деталь к факту привычки. Возвращает обновлённый факт или None,
    если такой привычки в дне почему-то нет.

    Деталь держим текстом рядом с фактом: «две чашки, последняя в пять» точнее
    любой цифры, которую мы бы из неё вытащили, а для поиска связей важно само
    наличие привычки, оно уже записано.
    """
    import dataclasses

    detail = text.strip()
    for index, fact in enumerate(record.facts):
        if fact.kind == "factor" and fact.name == factor and fact.value > 0:
            # Факт неизменяемый - собираем новый с дописанной деталью.
            # Пометка нужна, чтобы отличить уточнение от обычной цитаты: её
            # разборщик кладёт в каждый факт, и без пометки бот считал бы
            # уточнённым всё подряд и не спрашивал деталей вовсе.
            marked = f"{DETAIL_MARK}{detail}"
            quote = f"{fact.quote} / {marked}" if fact.quote else marked
            updated = dataclasses.replace(fact, quote=quote)
            record.facts[index] = updated
            return updated
    return None


class Parser:
    """
    Разбор речи: сначала модель, при сбое или пустом ответе - правила.

    Правила не заглушка, а страховка: продукт не должен вставать из-за
    недоступного сервиса.
    """

    def __init__(self, engine: str = "правила", complete=None) -> None:
        self.engine = engine
        self.rules = RuleExtractor()
        self.model = LLMExtractor(complete) if complete and engine != "правила" else None
        # Почему модель не сработала в прошлый раз. Пустая строка - всё в
        # порядке. Нужна, чтобы страница не врала: пока откат на словарь был
        # молчаливым, человек читал «речь разбирает Claude» и не понимал, почему
        # разбор вдруг стал хуже. А причина бывает простая - кончились деньги
        # на ключе или нет сети.
        self.last_error = ""

    @classmethod
    def from_environment(cls) -> "Parser":
        """Модель, для которой в окружении есть ключ, иначе правила."""
        engine, complete = available_engine()
        return cls(engine, complete)

    def parse(self, text: str, day: date, context: str = "") -> DayRecord:
        """
        Модель и правила дополняют друг друга, а не заменяют.

        Раньше ответ модели принимался целиком, как только в нём был хоть один
        факт, и правила уже не смотрели фразу. Модель отвечает неодинаково: во
        фразе «пил кофе в пять, спал часов пять, тревожно» она то возвращает
        тревогу, то нет - и тогда тревога терялась, хотя правила её видят.
        Поэтому берём разбор модели и дописываем то, что она пропустила.
        """
        by_rules = self.rules.extract(text, day)
        if self.model is None:
            return by_rules

        try:
            record = self.model.extract(text, day, context)
        except Exception as error:
            self.last_error = str(error)[:200]
            return by_rules
        self.last_error = ""
        if not record.facts:
            return by_rules

        # Что модель уже назвала - её и оставляем: она понимает живую речь
        # лучше словаря. Правила добавляют только пропущенное.
        known = {(f.kind, f.name) for f in record.facts}
        for fact in by_rules.facts:
            if (fact.kind, fact.name) not in known:
                record.add(fact)
        return record


_DEFAULT: Parser | None = None


def default_parser() -> Parser:
    """Разборщик по умолчанию. Собирается при первом обращении, не при импорте."""
    global _DEFAULT
    if _DEFAULT is None:
        _DEFAULT = Parser.from_environment()
    return _DEFAULT


# Сколько последних реплик разговора показываем модели как контекст. Две -
# это «что человек сказал» и «что мы ответили»: ровно то, к чему относится
# поправка вроде «нет, вру» или «а вообще ближе к шести». Больше не нужно:
# дальше начинается вчерашний день, и модель начнёт записывать его заново.
CONTEXT_MESSAGES = 4


def _recent(diary: Diary) -> str:
    """Последние реплики разговора одной строкой - контекст для разбора."""
    lines = []
    for message in diary.messages[-CONTEXT_MESSAGES:]:
        who = "Человек" if message["kind"] == "me" else "Дневник"
        lines.append(f"{who}: {message['text']}")
    return "\n".join(lines)


def parse_day(text: str, day: date, parser: Parser | None = None,
              context: str = "") -> DayRecord:
    return (parser or default_parser()).parse(text, day, context)


# Внутри программы шкала одна: больше - лучше самочувствие, поэтому стресс
# хранится перевёрнутым (2,8 означает высокий стресс). Считать так удобно, а
# читать - нет: рядом стояли «высокий стресс (с кольца)» и «стресс 2,8 из 10»,
# и это выглядело как противоречие. Человеку показываем в привычную сторону.
# Показываем в ту же сторону, в какую человек про это говорит. Список один
# на программу - в questions.ASKED_INVERTED, чтобы вопрос, ответ и показ не
# разъехались: именно из-за такого расхождения «тревога на 8» записывалась
# как спокойный день.
from .questions import ASKED_INVERTED as _TOLD_INVERTED


def _as_told(name: str, value: float) -> tuple[str, float]:
    """Как показать показатель человеку: имя и значение в привычную сторону."""
    if name in _TOLD_INVERTED:
        return name, round(10 - value, 1)
    return name, value


def facts_note(facts: list[Fact]) -> str:
    """
    Показываем только то, что было, и сами показатели. Строки вида
    «много двигался: не было» человеку не нужны - это шум.

    На вход идут факты одной реплики, а не вся запись за день: пока сюда
    отдавали день целиком, на каждую фразу бот перечислял всё накопленное с
    утра, в том числе когда в самой фразе не понял ничего.
    """
    habits, metrics = [], []
    for fact in facts:
        if fact.kind == "event":
            continue        # события в поиске связей не участвуют, показывать их незачем
        mark = " (с кольца)" if fact.source in DEVICE_SOURCES else ""
        if fact.kind == "factor":
            if fact.value > 0:
                habits.append(f"{fact.name}{mark}")
            elif fact.source in ("diary", ""):
                # «Не было» показываем, только когда это сказал сам человек.
                # Нули, посчитанные нами - с прибора, из погоды, из КБЖУ или
                # достроенные по молчанию, - для него шум: он их не называл.
                habits.append(f"{fact.name}: не было")
        else:
            name, value = _as_told(fact.name, fact.value)
            metrics.append(f"{name} {value:g} из 10{mark}")

    lines = []
    if habits:
        lines.append("Привычки: " + ", ".join(dict.fromkeys(habits)))
    if metrics:
        lines.append("Самочувствие: " + ", ".join(dict.fromkeys(metrics)))
    return "\n".join(lines)


def step(diary: Diary, text: str, ring: dict | None = None,
         links: list[Link] | None = None, parser: Parser | None = None,
         origin: str = "page", links_from_demo: bool = False,
         hints: list[Link] | None = None) -> list[dict]:
    """
    Шаг разговора и запись дневника на диск.

    Сохранение стоит здесь, а не у того, кто зовёт шаг: выходов из шага с
    десяток (вопрос задан, итог подведён, фраза не понята), и любой забытый
    означал бы потерянную запись. Запись дешёвая - на диск уходит только
    изменившийся день, - поэтому лишний вызов ничего не стоит.
    """
    said = _step(diary, text, ring=ring, links=links, parser=parser, origin=origin,
                 links_from_demo=links_from_demo, hints=hints)
    diary.save()
    return said


def _step(diary: Diary, text: str, ring: dict | None = None,
          links: list[Link] | None = None, parser: Parser | None = None,
          origin: str = "page", links_from_demo: bool = False,
          hints: list[Link] | None = None) -> list[dict]:
    """
    Один шаг разговора. Дописывает в ленту дневника сказанное человеком и ответ,
    возвращает только новые сообщения.

    links - связи, по которым задаём вопросы и делаем выводы. У бота это связи
    самого человека, у страницы пока придуманный дневник для показа, поэтому
    формулировка вывода немного разная.

    hints - связи с пониженным порогом (`Diary.hints`). Из них получаются
    наблюдения, которые дневник говорит, пока настоящих выводов ещё нет.

    Сетевых вызовов тут два - разбор речи моделью и погода, - и оба делаются до
    того, как берём замок дневника: держать замок во время запроса к сервису
    нельзя, иначе один медленный ответ останавливает и страницу, и бота.
    """
    links = links or []
    parsed = parse_day(text, date.today(), parser, context=_recent(diary))
    # Города нет - вернётся пустота, и погода в разговоре просто не участвует
    sky = weather.readings(diary.city)

    now = date.today()
    with diary.lock:
        # Пропуск считаем до того, как заведём сегодняшнюю запись: иначе
        # сегодняшний день уже стоит в дневнике и «последняя запись» - это он.
        missed = missed_days(diary.timeline, now)

        # Запись за сегодня заводим уже под замком: страница и чат в один
        # момент заводили две записи на один день, и половина фактов уезжала
        # в ту из них, которую потом никто не смотрел.
        record = diary.today()
        weather.attach(diary.timeline, sky)
        # Что из погоды вышло, человек должен услышать, а не только дневник:
        # пока строку никто не говорил, работающий источник выглядел как
        # неработающий - фактор молча ложился в день, и узнать про него было
        # неоткуда до самых выводов.
        sky_note = weather.day_note(sky.get(now), sky.get(now - timedelta(days=1)))
        before_seq = diary.seq
        pending = diary.pending_question(record.day)

        # Рассказ бывает про прошедший день: «вчера пил вино». Такую запись
        # кладём в тот день, а не в сегодняшний. Ответ на висящий вопрос так не
        # толкуем: «на 7, но вчера лёг рано» - это оценка за сегодня.
        #
        # Висящий вопрос день не глушит: `day_mentioned` и так смотрит только
        # первые два слова, а фраза, которая НАЧИНАЕТСЯ с «вчера» или «в
        # среду», - это рассказ про тот день, а не ответ на вопрос. Пока
        # висящий вопрос отменял разбор дня, «вчера пил вино» после «а как вы
        # себя чувствовали?» ложилось в сегодня - тихо и навсегда.
        spoken = day_mentioned(text, now)
        if spoken is not None:
            record = diary.record_for(spoken)

        diary.say("me", text, origin=origin)

        # Поправка дня - до всякого разбора: «а нет, вру, это был вторник» не
        # рассказ, а перенос уже записанного. Разбирать её как рассказ значило
        # бы записать вторник заново и оставить ошибку в прежнем дне.
        if _WRONG_DAY.search(text.lower()):
            other = day_mentioned(text, now, anywhere=True)
            if other is not None:
                moved = _move_day(diary, other, now, origin, before_seq)
                if moved:
                    return moved

        # Реплика бывает ответом и рассказом сразу: «на 3, вымотан после зала» -
        # это и оценка сил, и тренировка. Поэтому применяем оба разбора, а не
        # выбираем один: раньше половина сказанного пропадала, а вопрос уже
        # лежал в asked и второй раз не задавался.
        # Вопрос к программе ответом на её же вопрос не бывает: «что ты про
        # меня знаешь?» - это не «сколько выпили».
        question_to_us = asks_us(text)
        detail = "" if question_to_us else (detail_of(pending) if pending else "")
        # Спросили про самочувствие, а человек отвечает мерой: «часа полтора».
        # Это ответ про привычку, про которую шла речь, и терять его нельзя.
        # Но вопрос про самочувствие при этом остаётся висеть: на него-то не
        # ответили, а снимать чужой вопрос уточнением - терять оценку дня.
        guessed = False
        if not detail and pending and not question_to_us:
            detail = habit_for_measure(record, text)
            guessed = bool(detail)
        answered = (bool(pending) and not question_to_us
                    and _answers(record, pending, text))
        # Из вопроса к программе берём только самочувствие: «третий день болит
        # голова, что выпить?» - это и жалоба, и вопрос, и терять симптом
        # нельзя. А привычки в таком вопросе - предмет разговора, а не дело
        # дня: «откуда ты знаешь, что кофе виноват» - не выпитый кофе.
        if question_to_us and parsed is not None:
            parsed.facts = [f for f in parsed.facts if f.kind == "metric"]
        added = _absorb(record, parsed)

        # Спросили деталь привычки («сколько чашек кофе») - ответ надо принять,
        # иначе разговор выглядит издевательством: бот сам спросил и сам же не
        # понял. Деталь дописываем к факту привычки, чтобы она осталась в дне.
        # Деталь - это ответ про меру, а не новый рассказ. Если в реплике есть
        # что записать («весь день на фастфуде»), она не уточнение к прошлой
        # привычке, даже когда похожа на него словом «весь».
        detail_only = False
        if detail and not answered and not added and _looks_like_detail(text):
            kept = _remember_detail(record, detail, text)
            if kept is not None:
                detail_only = True
                if not guessed:
                    diary.forget_question()   # спросили про меру - и получили
                    answered = True
                if kept not in added:
                    added = added + [kept]

        if answered:
            # Ответ кладём последним: он должен вытеснить оценку по умолчанию,
            # которую правила поставили тому же показателю («тревога какая-то»).
            apply_answer(record, pending, text)
            diary.forget_question()
            scored = _metric_fact(record, metric_of(pending))
            if scored is not None:
                # В «Записал» идёт итоговая оценка, а не догадка правил
                added = [f for f in added
                         if not (f.kind == "metric" and f.name == scored.name)]
                added.append(scored)
        elif pending and not _polite(text) and not question_to_us:
            # Не признали ответом - вопрос остаётся висеть, но не вечно. Иначе
            # он пропадал насовсем: спросить второй раз мешает asked, а
            # следующая реплика проверялась уже ни против чего. Реплика «на 7,
            # но это скорее из-за того что вчера лёг рано» так теряла и оценку,
            # и сам вопрос.
            #
            # «Привет» и «спасибо» срок вопроса не тратят: человек поздоровался,
            # а не попытался ответить. Иначе три вежливые реплики подряд гасили
            # вопрос, и настоящий ответ прилетал уже в пустоту.
            diary.wait_longer()

        return _answer(diary, record, text, added, answered, ring, links, origin,
                       links_from_demo, before_seq, hints or [], missed, now,
                       sky_note, parsed, detail_only)


def _answer(diary: Diary, record: DayRecord, text: str, added: list[Fact],
            answered: bool, ring: dict | None, links: list[Link], origin: str,
            links_from_demo: bool, before_seq: int,
            hints: list[Link], missed: list[date], now: date,
            sky_note: str = "", parsed: DayRecord | None = None,
            detail_only: bool = False) -> list[dict]:
    """
    Что сказать в ответ. Решаем по тому, что дала именно эта реплика: пока
    решение принималось по накопленной за день записи, на «привет» бот заново
    перечислял все привычки с утра и второй раз задавал тот же вопрос.

    Вызывается под замком дневника, сети тут нет.
    """
    # Показания с прибора - всегда про сегодня: на странице это ползунки, они
    # показывают сегодняшнее состояние. Когда человек рассказывает про вчера,
    # запись идёт во вчерашний день, а показания туда попадать не должны -
    # иначе в прошлом дне появляются выдуманные цифры, которых прибор не мерил.
    if ring and record.day == date.today():
        known = list(record.facts)
        readings = SberRingSource().read([{**ring, "date": record.day.isoformat()}])
        merge_into(diary.timeline, readings)
        derive_factors(diary.timeline)
        # Показания идут с каждой репликой, в том числе с «привет». Объявлять их
        # человеку имеет смысл только вместе с тем, что он рассказал сам: иначе
        # на приветствие он получает «Записал: мало спал (с кольца)».
        if added or answered:
            added = added + [f for f in record.facts if f not in known]

    # Тяжёлый день - горе, больница, увольнение - человек называет один раз, и
    # бодрое «Записал! А как вы себя чувствовали? хватит пары слов» после этого
    # перечёркивает весь дневник. Запись делаем как обычно (такие дни влияют на
    # сон и силы сильнее любой привычки), но говорим по-человечески и ни о чём
    # больше в эту реплику не спрашиваем: ни про меру привычки, ни про
    # пропущенные дни, ни про выводы.
    if _HEAVY.search(text.lower()):
        diary.forget_question()
        diary.wrapped_day = record.day       # итог дня тоже не нужен
        diary.say("bot", HEAVY_REPLY, note=facts_note(added) if added else "",
                  origin=origin)
        return diary.feed(before_seq)

    # «Третий день болит голова, что мне выпить?» - тут есть и что записать, и
    # прямой вопрос. Записать мало: человек спросил, и молчание в ответ он
    # читает как «меня не услышали». Поэтому запись идёт своим чередом, а
    # ответ про лекарства - сразу за ней, и дальше в эту реплику мы уже ни о
    # чём не спрашиваем: свой вопрос человек задал первым.
    medical = bool(_MEDICAL.search(text.lower()))

    if added:
        # Что записала эта реплика - помним до следующей: если человек поправит
        # день («это был вторник»), переносить надо ровно это.
        diary.last_added = list(added)
        diary.last_day = record.day

    if added:
        # Чем разобрана фраза - техническая деталь, человеку она не нужна.
        # А вот день назвать надо, если запись легла не в сегодняшний: человек
        # должен видеть, что его «вчера» мы поняли именно как вчера.
        when = "" if record.day == now else f" {for_day(record.day, now)}"
        # Ответ на вопрос про меру - это уточнение уже записанного, а не новая
        # запись. «Записал: тренировка» на «часа полтора» человек читает как
        # «он записал тренировку второй раз».
        head = "Уточнил" if detail_only else "Записал"
        diary.say("bot", f"{head}{when}:", note=facts_note(added), origin=origin)
    elif not answered:
        # Реплика ничего не добавила и ответом на вопрос не была - «Записал»
        # писать не о чем, отвечаем по-человечески.
        #
        # Но если человек повторил то, что уже записано, «не понял» - неправда
        # и обида: он-то сказал понятное. Так и говорим.
        if parsed is not None and parsed.facts and not asks_us(text):
            diary.say("bot", ALREADY_KNOWN, origin=origin)
            return diary.feed(before_seq)
        return _small_talk(diary, text, record.day, origin, before_seq)

    if medical:
        _answer_once(diary, MEDICAL_REPLY, origin)
        return diary.feed(before_seq)

    if _ABOUT_ME.search(text.lower()):
        diary.say("bot", _what_i_know(diary, record.day), origin=origin)
        return diary.feed(before_seq)

    # Сегодня человек просил не спрашивать - значит, не спрашиваем: ни про меру
    # привычки, ни про пропущенные дни. Запись при этом идёт как обычно.
    #
    # Если он сам вернулся с рассказом, тишину снимаем - но со следующей
    # реплики: спросить сразу после «ладно, ладно» значит не услышать просьбу.
    if diary.quiet_day == record.day:
        if added:
            diary.quiet_day = None
        return diary.feed(before_seq)

    # Про пропущенные дни спрашиваем раньше всего остального: вчерашний день
    # человек ещё помнит, а через неделю уже нет. Вопрос один и только один раз
    # за день - иначе возвращение в дневник выглядит как выговор.
    if missed and diary.gap_asked != now:
        asking = gap_question(missed, now)
        if asking:
            diary.gap_asked = now
            diary.say("ask", asking, origin=origin)
            return diary.feed(before_seq)

    # Говорим про то, что человек назвал ЭТОЙ фразой, а не про всё, что успел
    # рассказать за день: иначе он пишет про мясо и пиво, а в ответ слышит про
    # утренний кофе - и разговор выглядит бессвязным.
    habits = frozenset(f.name for f in added if f.kind == "factor" and f.value > 0)

    # Пока связей ещё нет, дневник не должен молчать: сегодняшний день видно на
    # фоне прежних уже на нескольких записях. Это наблюдения, а не выводы, и
    # называем мы их именно так.
    #
    # Наблюдение идёт ДО вопроса, а не вместо него: это одна строка про то, что
    # мы уже увидели, а не отдельная ветка разговора. Пока оно стояло после,
    # любой уточняющий вопрос про названную привычку («сколько пива?») выходил
    # из ответа раньше - и про эту самую привычку человек не слышал ничего.
    # Погода - такое же наблюдение про сегодня, и повторов боится так же:
    # держим её в том же diary.observed. Строка меняется вместе с числами дня,
    # поэтому за день она скажется один раз и назавтра не повторится слово в
    # слово. Обычная погода сюда не доходит вовсе - day_note молчит, пока не
    # сработал хоть один фактор.
    if sky_note and sky_note not in diary.observed:
        diary.observed.add(sky_note)
        diary.say("bot", sky_note, origin=origin)

    seen = observations(diary.timeline, record, habits, hints)
    fresh = [line for line in seen if line not in diary.observed]
    if fresh:
        diary.observed.update(fresh)
        diary.say("bot", "\n".join(fresh), origin=origin)

    # Длительное отклонение - не про сегодня, а про месяц, поэтому идёт после
    # наблюдений про день: сперва человек слышит про свою запись, потом про фон.
    # Редкость и повторы держит сам модуль.
    long_line = drift.notice(diary, record.day)
    if long_line:
        diary.say("bot", long_line, origin=origin)

    # Дошли до предела вопросов за день - дальше работаем с тем, что рассказали.
    if len(diary.asked) >= MAX_QUESTIONS:
        question = None
    else:
        question = next_question(record, links, diary.asked, added=added, said=text)
    if question:
        if question == diary.pending:
            # Тот же вопрос второй раз подряд - самая быстрая причина бросить
            # дневник. Он и так висит, человек ответит на него, когда захочет.
            return diary.feed(before_seq)
        diary.expect(question, record.day)
        diary.asked.add(question)
        diary.say("ask", question, origin=origin)
        return diary.feed(before_seq)

    if not habits or (diary.concluded is not None and habits <= diary.concluded):
        return _wrap_up(diary, record, origin, before_seq)

    diary.concluded = (diary.concluded or frozenset()) | habits
    said = conclusions(habits, links, len(diary.timeline), links_from_demo)
    if not said:
        return _wrap_up(diary, record, origin, before_seq)

    diary.say("bot", "Картина дня понятна. Смотрю, что об этом говорит ваш дневник.",
              origin=origin)
    for message in said:
        diary.say(message["kind"], message["text"], message.get("note", ""), origin=origin)
    return diary.feed(before_seq)


def _wrap_up(diary: Diary, record: DayRecord, origin: str,
             before_seq: int) -> list[dict]:
    """
    Закрыть день, когда спрашивать больше нечего, а выводов ещё нет.

    Раньше разговор в этом месте просто обрывался: человек отвечал на последний
    вопрос, получал «Записал:» - и тишина. Выглядит как поломка, хотя программа
    просто закончила работу. Говорим, что записали и чего ждём дальше.
    """
    if diary.pending or diary.wrapped_day == record.day:
        return diary.feed(before_seq)       # вопрос ещё висит или итог уже сказан

    habits = [f.name for f in record.facts if f.kind == "factor" and f.value > 0
              and f.source not in DEVICE_SOURCES]
    if not habits:
        return diary.feed(before_seq)

    diary.wrapped_day = record.day
    days = len(diary.timeline)
    listed = ", ".join(dict.fromkeys(habits))
    if days < MIN_DAYS_FOR_HINT:
        left = MIN_DAYS_FOR_HINT - days
        diary.say("bot",
                  f"День записал: {listed}. Пока сравнивать почти не с чем - "
                  f"дней в дневнике {days}. Дней через {left} начну показывать, "
                  f"что с чем сходится. Если ещё что-то вспомните - допишите.",
                  origin=origin)
    else:
        diary.say("bot",
                  f"День записал: {listed}. Ничего нового про эти привычки пока "
                  f"не вижу - продолжаю следить. Если ещё что-то вспомните, "
                  f"допишите, это лишним не будет.",
                  origin=origin)
    return diary.feed(before_seq)


# ── когда отвечать нельзя как обычно ──────────────────────────────────────

# Тяжёлое событие. «Умер дедушка, весь день на похоронах» и в ответ бодрое
# «Записал! А как вы себя чувствовали? хватит пары слов» - это то, после чего
# дневник закрывают навсегда. Запись всё равно нужна: горе влияет на сон и силы
# сильнее любого кофе. Но сказать сначала надо по-человечески.
# Слова берём те же, по которым `extract` заводит фактор «тяжёлое событие»:
# два своих списка неизбежно разъедутся, и тогда бот будет то записывать день
# как тяжёлый, но отвечать бодро, то наоборот.
_HEAVY = re.compile(_HEAVY_WORDS)

HEAVY_REPLY = ("Сочувствую. Записал - такие дни на самочувствие влияют сильнее "
               "всего остального, и это важно помнить.\n"
               "Расскажете про день, когда будет силы, - или не рассказывайте, "
               "я подожду.")

# Вопрос про лекарства и лечение. Молчать нельзя: человек спросил прямо и
# решит, что его не услышали. Отвечать по существу - тоже: по дневнику отличить
# мигрень от давления, обезвоживания или недосыпа невозможно, и любой совет тут
# будет угадыванием.
_MEDICAL = re.compile(
    r"что (?:мне )?(?:выпить|принять|попить)|какие таблет|какое лекарств|"
    r"чем лечить|как лечить|что делать с (?:голов|давлен|болью)|"
    r"мне обследоват|надо к врачу|сдать анализ|какие анализ|"
    r"что со мной|чем я болен|это опасно")

MEDICAL_REPLY = (
    "Про лекарства и лечение я не советую - и не притворяюсь, что могу: по "
    "записям в дневнике причину не отличить, а угадывать тут нельзя.\n"
    "Что могу: собрать ваши записи за все дни в одну выгрузку - кнопка «Выгрузить "
    "дневник». С ней разговор с врачом выйдет предметнее, чем «мне плохо».")

# Вопрос про саму программу. «Ты живая или программа?» с ответом «не понял, что
# записать» - худший возможный ответ: человек спросил именно потому, что
# усомнился, и получил подтверждение худшего.
_WHO_ARE_YOU = re.compile(
    r"ты (?:вообще |реально |правда |что,? |сейчас )*"
    r"(?:живая|живой|человек|бот|программа|робот|настоящ\w*|кто)|"
    r"кто ты|это бот|с кем я говорю|ты ии|ты нейросет")

WHO_REPLY = ("Программа. Речь разбирает языковая модель, а связи между вашими "
             "днями считает обычная статистика - поэтому выводы можно проверить, "
             "а не просто поверить.\n"
             "Записи хранятся у вас на компьютере и никуда не уходят.")


# Поправка дня: «а нет, вру, это был вторник», «это было вчера, не сегодня».
# Человек не переписывает рассказ заново - он поправляет дату. Раньше такая
# реплика уходила в «не понял», а запись оставалась висеть не в том дне и
# портила статистику навсегда.
_WRONG_DAY = re.compile(
    r"^\s*(?:а\s+)?(?:нет|не)[,\s]|^\s*(?:вру|вернее|точнее|ошибся|ошиблась)|"
    r"\bэто был[оа]?\b|\bне сегодня\b|\bперепутал")


def _move_day(diary: Diary, to_day: date, now: date, origin: str,
              before_seq: int) -> list[dict]:
    """
    Перенести прошлую запись в другой день и сказать об этом.

    Переносим ровно то, что записала предыдущая реплика: остальное в том дне
    могло быть сказано раньше и к поправке отношения не имеет.
    """
    was = diary.last_day
    if was is None or was == to_day or not diary.last_added:
        return []

    source = diary.record_for(was)
    target = diary.record_for(to_day)
    moved = []
    for fact in list(diary.last_added):
        if fact in source.facts:
            source.facts.remove(fact)
            target.add(fact)
            moved.append(fact)
    if not moved:
        return []

    # Пустой день после переноса убираем: иначе в дневнике остаётся запись без
    # единого факта, и она считается прожитым днём в статистике.
    if not source.facts:
        diary.timeline.days = [d for d in diary.timeline.days if d.day != was]

    diary.last_day = to_day
    diary.last_added = moved
    diary.forget_question()
    diary.say("bot", f"Поправил: это было {day_name(to_day, now)}.",
              note=facts_note(moved), origin=origin)
    return diary.feed(before_seq)


# «Откуда ты знаешь, что кофе виноват? Может, совпадение» - это не запись дня,
# а самый важный вопрос, который человек может задать дневнику. Отвечать надо
# по существу: как именно считается связь и почему совпадение уже отброшено.
_HOW_SURE = re.compile(
    r"откуда ты (?:знаешь|взял|это)|почему ты (?:так )?(?:решил|думаешь|считаешь)|"
    r"может (?:это )?совпадени|это совпадени|с чего ты взял|ты уверен|"
    r"как ты (?:это )?(?:считаешь|посчитал|понял)|на чём основан|на чем основан|"
    r"докажи|это точно")

HOW_SURE_REPLY = (
    "Справедливый вопрос. Считаю так: беру ваши дни с этой привычкой и дни без "
    "неё и сравниваю показатель. Потом тысячу раз перемешиваю дни случайно и "
    "смотрю, часто ли такая же разница выходит сама собой. Если выходит - это "
    "совпадение, и я про него молчу.\n"
    "Ещё проверяю третий фактор: если в те же дни случалось что-то ещё и без "
    "него разница пропадает, я так и говорю - дело не в привычке.\n"
    "И всё равно это статистика, а не доказательство. Надёжнее один способ - "
    "проверить на себе: неделю с привычкой, неделю без.")

# «А если я вообще брошу кофе на неделю?» - человек сам предлагает эксперимент.
# Это ровно то, ради чего дневник и нужен, и отвечать на такое «не понял» -
# упустить главный разговор.
_TRY_WITHOUT = re.compile(
    r"если (?:я )?(?:вообще )?(?:брошу|перестану|уберу|откажусь|не буду|"
    r"завяжу|прекращу)|что будет если|попробовать без|прожить без|"
    r"недел\w* без")

TRY_WITHOUT_REPLY = (
    "Это и есть самая честная проверка. Схема простая: неделю живёте как "
    "обычно, неделю - без этой привычки, и каждый день отмечаете самочувствие "
    "парой слов.\n"
    "Через две недели сравню обе половины и скажу прямо: подтвердилось, не "
    "подтвердилось или данных не хватило. Начинайте, когда удобно, - я замечу "
    "по записям.")


# Раздражение и отказ. «Да достал ты со своими вопросами», «ничего не хочу
# сегодня писать» - это не бессмыслица, а прямая просьба отстать. Ответ «не
# понял, что записать» на неё выглядит как издевательство, а следующий вопрос
# добивает: человек закрывает дневник и не возвращается.
_ANNOYED = re.compile(
    r"достал|заколебал|отстань|отвали|хватит вопрос|сколько можно|"
    r"не хочу (?:писать|рассказывать|отвечать)|"
    r"ничего не (?:хочу|буду) (?:писать|рассказывать)|"
    # «не сегодня» отсюда убрано намеренно: «не сегодня, а позавчера» - это
    # поправка дня, а не отказ, и дневник отвечал на неё «вопросов больше не
    # будет» вместо переноса записи.
    r"сегодня не (?:буду|хочу|могу)|"
    r"без вопросов|перестань спрашивать")

ANNOYED_REPLY = ("Понял, вопросов на сегодня больше не будет. Дневник от этого "
                 "не испортится: что записано - то записано.\n"
                 "Захотите рассказать - просто напишите, я тут.")

# Куда уходят записи. Вопрос законный, и отвечать на него надо прямо, а не
# «не понял»: человек решает, доверять ли программе свои дни.
_PRIVACY = re.compile(
    r"(?:данные|записи|дневник)\w*.{0,25}(?:переда|продаёшь|продаешь|"
    r"отправля|сливаешь|уход|храни|хранятся|видит|видят)|"
    r"кто (?:это )?(?:видит|читает)|это конфиденциальн|куда уход|"
    r"на сервер|в облак")

PRIVACY_REPLY = (
    "Записи лежат в файле на вашем компьютере и никуда сами не уходят. "
    "Наружу отправляется только текст реплики - в языковую модель, чтобы её "
    "разобрать; если ключа модели нет, разбор идёт по словарю и не уходит "
    "никуда вообще.\n"
    "Выгрузить всё к себе или стереть можно в любой момент - кнопки «Выгрузить "
    "дневник» и «Начать заново».")

# Просьба стереть. Делать это сами не вправе - удаление необратимо, - но и
# отмолчаться нельзя: человек имеет право забрать свои записи.
_DELETE = re.compile(
    r"удали|сотри|стереть|очисти|забудь всё|забудь все|"
    r"начать заново|обнули")

DELETE_REPLY = ("Стереть всё можно кнопкой «Начать заново» - она внизу "
                "страницы, и после неё дневник будет пустым.\n"
                "Сам я записи не удаляю: отменить это нельзя, и решать тут "
                "вам. Если нужна копия перед удалением - «Выгрузить дневник».")


# «Что ты про меня знаешь?», «что там у меня?», «какие выводы?» - это вопрос
# про дневник, а не запись дня. Отвечать на него «не понял, что записать» -
# самый быстрый способ показать человеку, что перед ним форма ввода.
_ABOUT_ME = re.compile(
    r"(что|чего|чё|скольк\w*).{0,30}"
    r"(знаешь|известн\w*|запис\w*|помнишь|нашл\w*|виде?шь|выяснил\w*)"
    r"|какие выводы|что там у меня|что по мне|расскажи про меня"
    r"|что ты (обо мне|про меня)"
    # «Ну а ты что скажешь?» - человек просит дневник высказаться. Это тот же
    # вопрос про себя, только заданный вежливо, и «не понял» на него - обидно.
    r"|(?:а )?ты что (?:скажешь|думаешь|видишь)|что (?:ты )?скажешь"
    r"|тво[её] мнение|как тебе это|что думаешь")


def _what_i_know(diary: Diary, day: date) -> str:
    """
    Что известно про человека - человеческим языком. Не «данных мало», а
    сколько дней, что записано сегодня и когда ждать выводов.
    """
    days = len(diary.timeline)
    today = next((r for r in diary.timeline.days if r.day == day), None)
    habits = [f.name for f in (today.facts if today else [])
              if f.kind == "factor" and f.value > 0 and f.source not in DEVICE_SOURCES]
    metrics = [f"{f.name} {as_told(f.name, f.value):g} из 10"
               for f in (today.facts if today else []) if f.kind == "metric"]

    lines = [f"Дней в дневнике: {days}."]
    if habits:
        lines.append("Сегодня записано: " + ", ".join(dict.fromkeys(habits)) + ".")
    if metrics:
        lines.append("Самочувствие: " + ", ".join(dict.fromkeys(metrics)) + ".")

    links = [l for l in diary.links() if l.strength != "наблюдение"]
    if links:
        lines.append("Что уже вижу: " + say(links[0]))
    elif days < MIN_DAYS_FOR_HINT:
        left = MIN_DAYS_FOR_HINT - days
        lines.append(f"Выводов пока нет: нужно ещё {days_count(left)} записей, "
                     f"чтобы было с чем сравнивать.")
    else:
        lines.append("Надёжных связей пока не набралось - продолжаю следить.")
    lines.append("Все выводы разом - кнопкой «Показать все выводы» на странице.")
    return "\n".join(lines)


def asks_us(text: str) -> bool:
    """
    Реплика - вопрос к программе, а не рассказ про день: «что ты про меня
    знаешь?», «ты вообще живая?», «что мне выпить?».

    Нужно до разбора: пока такой вопрос шёл общим путём, он засчитывался
    ответом на висящий вопрос («сколько выпили?») и уходил в дневник деталью
    привычки - человек спрашивал, а в ответ получал «Записал: алкоголь».
    """
    lowered = (text or "").strip().lower()
    if not lowered:
        return False
    return bool(_MEDICAL.search(lowered) or _WHO_ARE_YOU.search(lowered)
                or _ABOUT_ME.search(lowered) or _PRIVACY.search(lowered)
                or _DELETE.search(lowered) or _ANNOYED.search(lowered)
                or _HOW_SURE.search(lowered) or _TRY_WITHOUT.search(lowered))


# Подсказки «не понял» по порядку: каждая следующая короче и мягче.
_NOT_UNDERSTOOD_LADDER = (NOTHING_UNDERSTOOD, NOTHING_UNDERSTOOD_AGAIN,
                          NOTHING_UNDERSTOOD_LAST)

# То же самое, когда вопрос уже висит: повторять его нельзя, а молчать невежливо.
DID_NOT_GET_IT_AGAIN = ("Всё равно не разобрал. Можно совсем просто: "
                        "«спал плохо», «был зал», «тревожно».")
DID_NOT_GET_IT_LAST = ("Ладно, не буду мучить. Напишете, когда будет что "
                       "записать - я тут.")

_DID_NOT_GET_LADDER = (DID_NOT_GET_IT, DID_NOT_GET_IT_AGAIN, DID_NOT_GET_IT_LAST)


# Короткий вариант готового ответа - на случай, когда человек спрашивает о том
# же второй раз. Слово в слово повторённый абзац читается как автоответчик:
# «спор» в прогоне разговоров выдавал один и тот же текст про эксперимент три
# реплики подряд.
SHORT_AGAIN: dict[str, str] = {}

# Третий раз объяснять то же самое незачем - лучше честно сказать, что уже
# рассказали, и не занимать человеку экран.
ALREADY_SAID = ("Про это я уже рассказал выше. Если что-то осталось непонятным - "
                "спросите иначе, отвечу подробнее.")


def _answer_once(diary: Diary, text: str, origin: str) -> None:
    """
    Сказать готовый ответ. Второй раз - короче, третий - отсылкой к сказанному.
    """
    said = [message["text"] for message in diary.messages]
    short = SHORT_AGAIN.get(text, "")
    if text not in said:
        diary.say("bot", text, origin=origin)
    elif short and short not in said:
        diary.say("bot", short, origin=origin)
    else:
        diary.say("bot", ALREADY_SAID, origin=origin)


SHORT_AGAIN.update({
    HOW_SURE_REPLY: "Считаю всё так же: сравниваю ваши дни с привычкой и без "
                    "неё и проверяю, не выходит ли такая же разница случайно.",
    TRY_WITHOUT_REPLY: "Схема та же: неделя как обычно, неделя без привычки. "
                       "Скажете «начали» - буду считать дни.",
    ANNOYED_REPLY: "Понял, молчу. Записывать буду, спрашивать - нет.",
    DELETE_REPLY: "Стереть - кнопка «Начать заново» внизу страницы.",
    PRIVACY_REPLY: "Записи лежат у вас на компьютере; наружу уходит только "
                   "текст реплики - в модель, чтобы её разобрать.",
    MEDICAL_REPLY: "Про лечение по-прежнему не советую. Могу собрать выгрузку "
                   "для врача - кнопка «Выгрузить дневник».",
    WHO_REPLY: "Программа. Речь разбирает модель, связи считает статистика.",
})


def _small_talk(diary: Diary, text: str, day: date, origin: str,
                before_seq: int) -> list[dict]:
    """Ответ на реплику, в которой мы ничего не разобрали."""
    lowered = text.strip().lower()
    if _HOW_SURE.search(lowered):
        _answer_once(diary, HOW_SURE_REPLY, origin)
    elif _TRY_WITHOUT.search(lowered):
        _answer_once(diary, TRY_WITHOUT_REPLY, origin)
    elif _ANNOYED.search(lowered):
        diary.quiet_day = day
        diary.forget_question()
        _answer_once(diary, ANNOYED_REPLY, origin)
    elif _DELETE.search(lowered):
        _answer_once(diary, DELETE_REPLY, origin)
    elif _PRIVACY.search(lowered):
        _answer_once(diary, PRIVACY_REPLY, origin)
    elif _MEDICAL.search(lowered):
        diary.say("bot", MEDICAL_REPLY, origin=origin)
    elif _WHO_ARE_YOU.search(lowered):
        _answer_once(diary, WHO_REPLY, origin)
    elif _ABOUT_ME.search(lowered):
        diary.say("bot", _what_i_know(diary, day), origin=origin)
    elif _GREETING.match(lowered):
        diary.say("bot", GREETING_REPLY, origin=origin)
    elif _THANKS.match(lowered):
        diary.say("bot", THANKS_REPLY, origin=origin)
    elif _bare_score(lowered) or _SCORE_PHRASE.search(lowered):
        # Голая оценка - «на 4» - осмысленная реплика: человек называет балл,
        # просто не сказал чему. Отвечать на неё «не понял» - обидно и неверно;
        # спрашиваем прямо, про что это. Раньше так отвечали только на вопрос
        # «как вы себя чувствовали?», а без висящего вопроса человек получал
        # «не понял» на собственное уточнение.
        #
        # Но спрашивать одно и то же второй раз - тупик: человек уже ответил
        # так, как умеет. Тогда записываем самой общей оценкой - настроением, -
        # и честно говорим, что записали и как поправить.
        asked_before = any(m["text"].endswith(WHICH_METRIC_TAIL)
                           for m in diary.messages)
        score = _score_said(lowered)
        if asked_before and score is not None:
            record = diary.record_for(day)
            fact = Fact("metric", "настроение", score, "diary", quote=text)
            record.add(fact)
            diary.say("bot",
                      "Записал как настроение - это самая общая оценка дня. "
                      "Если это было про сон или тревогу, скажите словом, поправлю.",
                      note=facts_note([fact]), origin=origin)
        else:
            diary.say("bot", which_metric(lowered), origin=origin)
    elif diary.pending:
        # Тот же приём, что и с подсказкой ниже: одно и то же «не понял» три
        # раза подряд человек читает как поломку. Второй раз - другими
        # словами, третий - отходим в сторону и ждём.
        said_before = sum(1 for m in diary.messages if m["text"] in _DID_NOT_GET_LADDER)
        step = min(said_before, len(_DID_NOT_GET_LADDER) - 1)
        diary.say("bot", _DID_NOT_GET_LADDER[step], origin=origin)
    else:
        # Вопросов не ждём - значит, самое время подсказать, как рассказать.
        # Каждый следующий раз подсказка другая и короче: одна и та же фраза
        # третий раз подряд выглядит как сломанный автомат.
        said_before = sum(1 for m in diary.messages
                          if m["text"] in _NOT_UNDERSTOOD_LADDER)
        hint = _NOT_UNDERSTOOD_LADDER[min(said_before, len(_NOT_UNDERSTOOD_LADDER) - 1)]
        if hint is NOTHING_UNDERSTOOD_LAST:
            diary.say("bot", hint, origin=origin)     # уже не вопрос, а пауза
        else:
            diary.expect(hint, day)
            diary.say("ask", hint, origin=origin)
    return diary.feed(before_seq)


def conclusions(habits: frozenset[str] | set[str], links: list[Link], days: int = 0,
                links_from_demo: bool = False) -> list[dict]:
    """
    Что известно про названные привычки. Пустой список - сказать нечего.

    Принимает именно набор привычек, а не запись за день: говорить надо про то,
    что человек назвал сейчас.
    """
    found = [l for l in links if l.factor in habits and l.strength != "наблюдение"]
    if not found:
        if days < MIN_DAYS_FOR_HINT:
            # В начале дневника «выводов пока нет» на каждую фразу звучит как
            # отписка: их и не может быть, пока дней мало. Молчим.
            return []
        return [{"kind": "bot", "note": f"Дней в дневнике: {days}.",
                 "text": "Про эти привычки выводов пока нет: нужно хотя бы семь дней "
                         "с привычкой и семь дней без неё. Продолжайте записывать."}]

    head = ("Вот что про эти привычки говорит придуманный дневник за несколько месяцев - "
            "на ваших записях выводы появятся так же, недели через три."
            if links_from_demo else
            "Вот что про эти привычки говорит ваш дневник.")
    return ([{"kind": "bot", "text": head}]
            + [{"kind": "result", "text": say(l), "note": f"{basis(l)} {next_step(l)}"}
               for l in found])


def _absorb(record: DayRecord, parsed: DayRecord | None) -> list[Fact]:
    """
    Дописать разобранное в запись дня и вернуть то, что правда добавилось.

    Именно добавившееся мы потом и показываем: про кофе, названный час назад,
    второй раз говорить «записал» не нужно.
    """
    added = []
    for fact in (parsed.facts if parsed else []):
        known = list(record.facts)
        record.add(fact)             # тот же показатель за день не удваивается
        if fact in record.facts and fact not in known:
            added.append(fact)
    return added


def _metric_fact(record: DayRecord, metric: str) -> Fact | None:
    """Факт-показатель за день целиком, вместе с оценкой - для показа человеку."""
    return next((f for f in record.facts if f.kind == "metric" and f.name == metric), None)


def _answers(record: DayRecord, question: str, text: str) -> bool:
    """
    Есть ли в реплике оценка по заданному вопросу. Спрашиваем ровно тот же
    разбор, который потом впишет ответ в дневник.

    Ответ на вопрос со шкалой - это оценка: «на 7», «часов шесть», «нормально».
    Наличие рассказа рядом с оценкой ей не мешает - «на 3, вымотан после зала»
    это и оценка сил, и тренировка. А вот число при мере оценкой не бывает:
    «спал 5 часов» в ответ про тревогу давало «тревога 5», «сегодня 8 встреч» -
    «тревога 8». Вопрос про сон - исключение: часы там и есть ответ.

    Развёрнутый рассказ ответом не считаем вовсе: в нём число почти наверняка
    про что-то своё, а оценку человек ещё успеет назвать - вопрос останется.

    Раньше ответ искали по разнице значений в записи, и совпадение с догадкой
    правил читалось как молчание: на «тревога какая-то» правила ставят 3.0, и
    честное «3» от человека вопрос не закрывало.
    """
    if len(text.split()) > MAX_ANSWER_WORDS:
        return False

    if score_in(question, text, record.day) is None:
        return False        # оценки в реплике не нашлось

    return metric_of(question) == "качество сна" or not measured_number(text)
