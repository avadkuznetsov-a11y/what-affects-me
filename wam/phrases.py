# Оговорка про дни «без привычки», которые мы достроили сами (`wam.habits`).
# Убирать её нельзя: половина сравнения держится на догадке, и человек имеет
# право знать об этом до того, как поверит выводу.
IMPLIED_NOTE = ("Днями без привычки считаем те, когда вы писали в дневник и про неё "
                "не вспомнили. Если было наоборот - скажите, и я поправлю день.")


def factor_phrase(name: str) -> str:
    return _FACTOR_PHRASE.get(name, f"В дни, когда было «{name}»")


def metric_phrase(metric: str, worse: bool) -> str:
    pair = _WORDING.get(metric)
    if pair:
        return pair[0] if worse else pair[1]
    return f"«{metric}» {'хуже' if worse else 'лучше'}"


def say(link: Link) -> str:
    """Главная фраза: что происходит и насколько."""
    worse = link.effect < 0
    change = metric_phrase(link.metric, worse)
    amount = abs(link.effect)

    if link.confounder:
        start = factor_phrase(link.factor)
        if "," in start:
            start += ","
        return (f"{start} {change}, но дело, скорее всего, не в этом: "
                f"виноват другой фактор - {link.confounder}.")

    strength = "заметно" if amount >= 1.5 else "немного"
    when = "на следующий день" if link.lag_days == 1 else (
        "через день" if link.lag_days == 2 else "в тот же день")
    # «После ночей, когда вы мало спали» - придаточное нужно закрыть запятой,
    # иначе фраза читается сплошняком
    start = factor_phrase(link.factor)
    if "," in start:
        start += ","
    return f"{start} {when} {change}, и {strength}: на {_score(amount)} из 10."


def basis(link: Link) -> str:
    """Откуда это известно - чтобы человек понимал, на чём вывод держится."""
    source = {"прибор": "по данным кольца",
              "погода": "по погоде в вашем городе",
              "еда": "по вашим числам о еде"}.get(link.source, "по вашим записям")
    days = f"{days_count(link.days_with)} с этим и {link.days_without} без"

    if link.confounder:
        return (f"В такие дни «{link.confounder}» случается чаще обычного, и когда мы "
                f"сравниваем дни отдельно с ним и отдельно без него, разница пропадает.")
    if link.strength == "подтверждено":
        said = f"Сравнили {days}, {source}. Совпадением это уже не объяснить."
    else:
        said = f"Сравнили {days}, {source}. Пока похоже на правду, но данных маловато."
    return f"{said} {IMPLIED_NOTE}" if link.implied_without else said


def days_count(count: int) -> str:
    """День, дня, дней - иначе фраза спотыкается на числах."""
    return f"{count} {_form(count, 'день', 'дня', 'дней')}"


def _form(count: int, one: str, few: str, many: str) -> str:
    """Форма слова при числе: 1 день, 2 дня, 5 дней, 11 дней."""
    if 11 <= count % 100 <= 14:
        return many
    last = count % 10
    if last == 1:
        return one
    if 2 <= last <= 4:
        return few
    return many


def period(days: int) -> str:
    """
    Срок словами: «21 день», «3 месяца», «полгода». Раньше срок склеивался на
    ходу («{days} дней», «{days // 30} месяца») и получались «21 дней» и
    «6 месяца» - число человек выбирает сам, а окончание никто не считал.
    """
    if days < 60:
        return days_count(days)
    months = round(days / 30)
    if months == 6:
        return "полгода"
    if months == 12:
        return "год"
    return f"{months} {_form(months, 'месяц', 'месяца', 'месяцев')}"


def _score(amount: float) -> str:
    """Балл по-русски: с запятой и в нужном падеже."""
    text = f"{amount:.1f}".replace(".", ",")
    whole = int(amount)
    if amount == whole:
        word = "балл" if whole % 10 == 1 and whole % 100 != 11 else (
            "балла" if 2 <= whole % 10 <= 4 and not 12 <= whole % 100 <= 14 else "баллов")
        return f"{whole} {word}"
    return f"{text} балла"


def next_step(link: Link) -> str:
    """Что делать дальше."""
    if link.confounder:
        return f"Проверять стоит не это, а «{link.confounder}»."
    if link.lag_days == 0:
        return ("Что было раньше - непонятно: и то и другое случилось в один день. "
                "Проверим экспериментом.")
    return "Это можно проверить: две недели с фактором, две без, и посмотрим на разницу."


def full(link: Link) -> str:
    """Всё вместе, для мессенджера."""
    return f"{say(link)} {basis(link)} {next_step(link)}"
