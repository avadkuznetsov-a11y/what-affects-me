"""
Как рассказать про найденную связь человеку.

Внутри программы связь описана честно и сухо: фактор, метрика, задержка,
разница средних, уровень значимости. Человеку так говорить нельзя - он не
статистик и не обязан им быть. Здесь эти же данные превращаются в обычную
фразу, которую можно прочитать вслух.

Правило простое: сначала говорим суть, потом откуда это известно, и только
если связь сомнительная - объясняем, почему.
"""
from __future__ import annotations

from .insights import Link

# Как назвать изменение метрики словами. Шкала везде такая: больше - лучше.
_WORDING: dict[str, tuple[str, str]] = {
    # метрика:          (стало хуже,            стало лучше)
    "качество сна":     ("спится хуже",         "спится лучше"),
    "энергия":          ("меньше сил",          "больше сил"),
    "тревога":          ("тревожнее",           "спокойнее"),
    "настроение":       ("настроение хуже",     "настроение лучше"),
    "головная боль":    ("голова болит чаще",   "голова болит реже"),
    "стресс":           ("больше напряжения",   "меньше напряжения"),
    "пульс покоя":      ("пульс выше",          "пульс ниже"),
    "активность":       ("двигаетесь меньше",   "двигаетесь больше"),
}

# Как назвать сам фактор в начале фразы
_FACTOR_PHRASE: dict[str, str] = {
    "кофе":             "После кофе",
    "алкоголь":         "После алкоголя",
    "тренировка":       "В дни с тренировкой",
    "перелёт":          "После перелёта",
    "много встреч":     "В дни, забитые встречами",
    "поздний отбой":    "После позднего отбоя",
    "экран перед сном": "После экрана перед сном",
    "прогулка":         "В дни с прогулкой",
    "сладкое":          "В дни со сладким",
    "аврал":            "В аврал на работе",
    "мало спал":        "После ночей, когда вы мало спали",
    "хорошо выспался":  "После ночей, когда вы выспались",
    "мало двигался":    "После дней без движения",
    "много двигался":   "После дней с большой активностью",
    "высокий стресс":   "После дней с высоким напряжением",
    "высокий пульс":    "После дней с высоким пульсом",
}


def factor_phrase(name: str) -> str:
    return _FACTOR_PHRASE.get(name, f"В дни, когда было «{name}»")


def metric_phrase(metric: str, worse: bool) -> str:
    pair = _WORDING.get(metric)
    if pair:
        return pair[0] if worse else pair[1]
    return f"«{metric}» {'хуже' if worse else 'лучше'}"


def say(link: Link) -> str:
    """Главная фраза: что происходит и насколько."""
    worse = link.effect < 0
    change = metric_phrase(link.metric, worse)
    amount = abs(link.effect)

    if link.confounder:
        start = factor_phrase(link.factor)
        if "," in start:
            start += ","
        return (f"{start} {change}, но дело, скорее всего, не в этом: "
                f"виноват другой фактор - {link.confounder}.")

    strength = "заметно" if amount >= 1.5 else "немного"
    when = "на следующий день" if link.lag_days == 1 else (
        "через день" if link.lag_days == 2 else "в тот же день")
    # «После ночей, когда вы мало спали» - придаточное нужно закрыть запятой,
    # иначе фраза читается сплошняком
    start = factor_phrase(link.factor)
    if "," in start:
        start += ","
    return f"{start} {when} {change}, и {strength}: на {_score(amount)} из 10."


def basis(link: Link) -> str:
    """Откуда это известно - чтобы человек понимал, на чём вывод держится."""
    source = "по данным кольца" if link.source == "прибор" else "по вашим записям"
    days = f"{_days(link.days_with)} с этим и {link.days_without} без"

    if link.confounder:
        return (f"В такие дни «{link.confounder}» случается чаще обычного, и когда мы "
                f"сравниваем дни отдельно с ним и отдельно без него, разница пропадает.")
    if link.strength == "подтверждено":
        return f"Сравнили {days}, {source}. Совпадением это уже не объяснить."
    return f"Сравнили {days}, {source}. Пока похоже на правду, но данных маловато."


def _days(count: int) -> str:
    """День, дня, дней - иначе фраза спотыкается на числах."""
    if 11 <= count % 100 <= 14:
        return f"{count} дней"
    last = count % 10
    if last == 1:
        return f"{count} день"
    if 2 <= last <= 4:
        return f"{count} дня"
    return f"{count} дней"


def _score(amount: float) -> str:
    """Балл по-русски: с запятой и в нужном падеже."""
    text = f"{amount:.1f}".replace(".", ",")
    whole = int(amount)
    if amount == whole:
        word = "балл" if whole % 10 == 1 and whole % 100 != 11 else (
            "балла" if 2 <= whole % 10 <= 4 and not 12 <= whole % 100 <= 14 else "баллов")
        return f"{whole} {word}"
    return f"{text} балла"


def next_step(link: Link) -> str:
    """Что делать дальше."""
    if link.confounder:
        return f"Проверять стоит не это, а «{link.confounder}»."
    if link.lag_days == 0:
        return ("Что было раньше - непонятно: и то и другое случилось в один день. "
                "Проверим экспериментом.")
    return "Это можно проверить: две недели с фактором, две без, и посмотрим на разницу."


def full(link: Link) -> str:
    """Всё вместе, для мессенджера."""
    return f"{say(link)} {basis(link)} {next_step(link)}"
