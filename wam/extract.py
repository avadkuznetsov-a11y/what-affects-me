# ── время суток ───────────────────────────────────────────────────────────
#
# Утренний кофе и кофе в шесть вечера - это разные вещи для сна, а утренняя
# пробежка и вечерняя по-разному влияют на засыпание. Пока время не различается,
# обе привычки лежат в дневнике как одна, и связь по ним выходит грубой.
#
# Границы обиходные, а не астрономические: человек говорит «утром» примерно про
# то же, что и все, а точность до часа тут ничего не добавит.
_PART_OF_DAY: list[tuple[str, str]] = [
    (r"с утра|утром|утренн\w*|на завтрак|до обеда", "утро"),
    (r"в обед|днём|днем|дневн\w*|после обеда", "день"),
    (r"вечером|под вечер|вечерн\w*|на ужин|после работы", "вечер"),
    (r"ночью|ночн\w*|перед сном|за полноч|под утро", "ночь"),
]

# Час, названный цифрой: «в 18», «в 6 вечера», «часов в пять».
_AT_HOUR = re.compile(r"\b(?:в|часов в|около)\s+(\d{1,2})(?:[:.](\d{2}))?\b")

_HOUR_WORDS = {"час": 13, "два": 14, "три": 15, "четыре": 16, "пять": 17,
               "шесть": 18, "семь": 19, "восемь": 20, "девять": 21,
               "десять": 22, "одиннадцать": 23, "двенадцать": 0}


# Привычки, для которых время суток правда меняет дело. Список короткий
# нарочно: каждый новый фактор - это ещё одна проверенная пара, а от их числа
# зависит поправка на множественные сравнения. Плодить «мясо утром» и «мясо
# вечером» значит ослабить все выводы разом ради сомнительной пользы.
TIME_MATTERS = {"кофе", "алкоголь", "тренировка", "прогулка"}


def timed_name(habit: str, when: str) -> str:
    """«кофе» + «вечер» -> «кофе вечером». Пустая строка - время не важно."""
    if habit not in TIME_MATTERS or not when:
        return ""
    return f"{habit} {_WHEN_WORD[when]}"


_WHEN_WORD = {"утро": "утром", "день": "днём", "вечер": "вечером", "ночь": "ночью"}


def part_of_day(text: str) -> str:
    """
    Когда это было: утро, день, вечер или ночь. Пустая строка - не сказано.

    Сначала ищем прямое слово («вечером»), потом час: «в шесть вечера» уже
    покрыто словом, а «в 18» - нет. Час без уточнения читаем по-обиходному:
    «в шесть» вечером люди говорят чаще, чем в шесть утра, но гадать не будем -
    берём только то, что названо однозначно.
    """
    lowered = (text or "").lower()
    for pattern, name in _PART_OF_DAY:
        if re.search(pattern, lowered):
            return name

    at = _AT_HOUR.search(lowered)
    if at:
        hour = int(at.group(1))
        # Уточнение стоит ПОСЛЕ часа: «в три ночи», «в шесть вечера». Без этого
        # «лёг в три ночи» читалось как день - три часа пополудни.
        after = lowered[at.end():at.end() + 12]
        if re.match(r"\s*(ночи|утра)", after):
            return "ночь" if "ноч" in after else "утро"
        if re.match(r"\s*(вечера|дня)", after):
            return "вечер" if "вечер" in after else "день"
        if hour <= 24:
            return _hour_part(hour)

    # «часов в пять», «около шести» - час словом
    for word, hour in _HOUR_WORDS.items():
        found = re.search(rf"(?:в|часов в|около)\s+{word}\b(\s*\w+)?", lowered)
        if not found:
            continue
        tail = (found.group(1) or "").strip()
        if tail.startswith("ноч"):
            return "ночь"
        if tail.startswith("утр"):
            return "утро"
        if tail.startswith("вечер"):
            return "вечер"
        if tail.startswith("дня"):
            return "день"
        return _hour_part(hour)
    return ""


def _hour_part(hour: int) -> str:
    """Час в часть суток. Границы обиходные: так люди и делят свой день."""
    if 5 <= hour < 12:
        return "утро"
    if 12 <= hour < 17:
        return "день"
    if 17 <= hour < 23:
        return "вечер"
    return "ночь"


def canonical_factor(name: str) -> str:
    """
    Свести имя привычки к общему. «Пробежка» и «зал» - это «тренировка»,
    «поздний отход ко сну» - «поздний отбой».

    Модель называет одно и то же по-разному, и промпт это не гарантирует:
    привычка расщеплялась на два фактора и статистики не набирала никогда.
    Дни без привычки считать научились, но если имя каждый раз новое, сравнивать
    всё равно нечего. Сводим по тому же словарю, по которому работают правила -
    так списки не разъедутся.

    Незнакомое имя оставляем как есть: «ссора с тёщей» и «переезд» тоже факторы,
    и придумывать им место в словаре мы не вправе.
    """
    name = (name or "").strip().lower()
    if not name:
        return ""
    for pattern, canonical in _FACTOR_PATTERNS:
        if re.search(pattern, name):
            return canonical
    return name

