# Привычки тоже считают штуками: «выпил 2 кофе», «2 пива вечером». Слова берём
# из словаря привычек, а не отдельным списком: свой список разъехался бы с
# _FACTOR_PATTERNS на первой же новой привычке.
_COUNTED = re.compile("|".join(pattern for pattern, _ in _FACTOR_PATTERNS))


def canonical_factor(name: str) -> str:
    """
    Свести имя привычки к общему. «Пробежка» и «зал» - это «тренировка»,
    «поздний отход ко сну» - «поздний отбой».

    Модель называет одно и то же по-разному, и промпт это не гарантирует:
    привычка расщеплялась на два фактора и статистики не набирала никогда.
    Дни без привычки считать научились, но если имя каждый раз новое, сравнивать
    всё равно нечего. Сводим по тому же словарю, по которому работают правила -
    так списки не разъедутся.

    Незнакомое имя оставляем как есть: «ссора с тёщей» и «переезд» тоже факторы,
    и придумывать им место в словаре мы не вправе.
    """
    name = (name or "").strip().lower()
    if not name:
        return ""
    for pattern, canonical in _FACTOR_PATTERNS:
        if re.search(pattern, name):
            return canonical
    return name

# Если человек просто назвал плохое состояние и не поставил оценку —
# считаем это низким баллом. Молчать в такой ситуации хуже, чем округлить:
# «тревога какая-то» это точно не десятка.
_NEGATIVE_BY_DEFAULT = {"тревога": 3.0, "головная боль": 3.0}


# ── Про какой день рассказывают ───────────────────────────────────────────
# Человек не обязан рассказывать только про сегодня: пропустил пару дней -
# и вспоминает их вслух, «вчера пил вино», «в среду был перелёт». Такую запись
# надо положить в ТОТ день, иначе она перепутает всю статистику.

_YESTERDAY = {"вчера": 1, "позавчера": 2}

# Дни недели: имя и номер, как их считает date.weekday() - понедельник ноль.
_WEEKDAYS: list[tuple[str, int]] = [
    (r"понедельник\w*", 0),
    (r"вторник\w*", 1),
    (r"сред[уыа]\b", 2),
    (r"четверг\w*", 3),
    (r"пятниц[уые]\b", 4),
    (r"суббот[уыа]\b", 5),
    (r"воскресень[еяю]\b", 6),
]

# Внутри скольких слов от начала фразы день считается её темой. Дальше это уже
# не «про какой день рассказ», а пояснение внутри рассказа про сегодня:
# «на 7, но это скорее из-за того что вчера лёг рано» - оценка за сегодня, и
# уводить её во вчера нельзя.
DAY_WORDS = 2

# Дальше недели назад по названию дня недели не уходим: «в среду» через две
# недели человек имеет в виду редко, а ошибка тут дорогая - факт ляжет не в
# тот день и в статистике останется навсегда.
_WEEK = 7


def day_mentioned(text: str, today: date) -> date | None:
    """
    Про какой прошедший день говорит фраза. None - про сегодня или непонятно.

    Смотрим только начало фразы: так люди и говорят, когда рассказывают про
    другой день. Про сегодняшний день ничего не возвращаем - он и так текущий.
    """
    lowered = text.strip().lower()
    if not lowered:
        return None
    # Граница «первых двух слов» в символах: считать слова по отдельности
    # незачем, нам нужно ровно одно - началась ли фраза с названия дня.
    words = re.split(r"\s+", lowered)[:DAY_WORDS]
    head = " ".join(words)

    for word, back in _YESTERDAY.items():
        if re.search(rf"\b{word}\b", head):
            return today - timedelta(days=back)

    for pattern, weekday in _WEEKDAYS:
        if not re.search(pattern, head):
            continue
        back = (today.weekday() - weekday) % _WEEK
        # «В среду», сказанное в среду, - это про сегодня: своим же днём
        # недели человек называет прошлую неделю крайне редко.
        return None if back == 0 else today - timedelta(days=back)

    return None


class Extractor(Protocol):
    """Любой разборщик рассказа — правила или модель."""

    def extract(self, text: str, day: date) -> DayRecord: ...


class RuleExtractor:
    """Разбор по правилам: быстрый, бесплатный, полностью офлайн."""

    def extract(self, text: str, day: date) -> DayRecord:
        record = DayRecord(day=day, raw_text=text)
        lowered = text.lower()

        for pattern, name in _FACTOR_PATTERNS:
            match = re.search(pattern, lowered)
            if not match:
                continue
            # «не пил кофе» — это факт об отсутствии фактора, а не о его наличии
            window = lowered[max(0, match.start() - 20):match.start()]
            value = 0.0 if _NEGATION.search(window) else 1.0
            record.add(Fact("factor", name, value, "diary", quote=_around(text, match.start())))

        for pattern, name in _METRIC_PATTERNS:
            match = re.search(pattern, lowered)
            if not match:
                continue
            score = _score_near(lowered, match.start(), metric=name)
            if score is None:
                score = _NEGATIVE_BY_DEFAULT.get(name)
            if score is not None:
                record.add(Fact("metric", name, score, "diary", quote=_around(text, match.start())))

        return record


class LLMExtractor:
    """
    Разбор моделью. Модель отвечает строгим JSON — свободный текст в ответе
    не принимается, иначе факты невозможно свести к общим именам.
    """

    # Список показателей закрытый: если модель придумает своё название,
    # связи по нему никогда не наберут статистики.
    METRICS = ("качество сна", "энергия", "тревога", "настроение", "головная боль")

    PROMPT = (
        "Ты разбираешь дневниковую запись человека. Верни СТРОГО JSON вида\n"
        '{"factors": [{"name": "...", "value": 1}], '
        '"metrics": [{"name": "...", "value": 7}], "events": ["..."]}\n'
        "Правила:\n"
        "1. factors - что человек делал или что с ним случилось. Имя короткое, в именительном "
        "падеже: «кофе», «тренировка», «перелёт», «работа», «ссора с руководителем». value: 1 "
        "если было, 0 если человек прямо говорит, что этого не было. Записывай КАЖДОЕ занятие, "
        "которое назвал человек, даже если в одной фразе их несколько.\n"
        "2. Одинаковые по смыслу формулировки своди к одному имени. Если привычка есть в "
        "списке ниже, бери имя ОТТУДА - слово в слово. Своё имя придумывай только для того, "
        "чего в списке нет («ссора с тёщей», «переезд»).\n"
        "   Список имён: " + ", ".join(name for _, name in _FACTOR_PATTERNS) + ".\n"
        "   Примеры сведения: «пробежка», «зал», «йога», «плавал» - «тренировка»; "
        "«лёг в три», «допоздна не спал» - «поздний отбой»; «вино», «пиво», «виски» - "
        "«алкоголь»; «созвон», «совещание» - «много встреч»; «дедлайн», «завал» - «аврал».\n"
        "2а. Еда - такой же фактор, как всё остальное, и её надо записывать. Своди её к "
        "этим именам: мясо, рыба, овощи, фастфуд, сладкое, выпечка, молочное, острое, "
        "поздний ужин, переедание, пропустил обед. «Ел много мяса» - «мясо»; «бургер», "
        "«пицца», «шаурма» - «фастфуд»; «наелся на ночь» - «поздний ужин»; «объелся» - "
        "«переедание»; «весь день на кофе», «забыл поесть» - «пропустил обед» (и «кофе», "
        "если кофе назван). Оценок еде не даём: полезная она или вредная - не наше дело.\n"
        "3. metrics - только из этого списка: качество сна, энергия, тревога, настроение, "
        "головная боль. Другие названия не придумывай.\n"
        "4. value у metrics - ЦЕЛОЕ число от 0 до 10, где 10 - отлично, 0 - хуже некуда. "
        "Это относится и к тревоге: сильная тревога это 2, спокойный день это 9. "
        "Восемь часов сна это 10, четыре часа это 5.\n"
        "5. Про самочувствие люди говорят обиняками, и это тоже оценка: «вымотался», "
        "«хотелось спать», «еле дожил до вечера» - энергия 2; «всё валится из рук», «грустно» - "
        "настроение 3; «места себе не находил» - тревога 2; «выспался», «бодрый» - энергия 8. "
        "Понимай такие слова, а не жди готовых оценок в баллах.\n"
        "6. Ничего не выдумывай: чего в записи нет, того нет в ответе. Но и не молчи там, "
        "где смысл понятен из обычной речи.\n"
        "\n"
        "Примеры разбора:\n"
        "Запись: гулял, пил вино, работал\n"
        '{"factors": [{"name": "прогулка", "value": 1}, {"name": "алкоголь", "value": 1}, '
        '{"name": "работа", "value": 1}], "metrics": [], "events": []}\n'
        "Запись: ел много мяса и фастфуд, к вечеру разбитый\n"
        '{"factors": [{"name": "мясо", "value": 1}, {"name": "фастфуд", "value": 1}], '
        '"metrics": [{"name": "энергия", "value": 3}], "events": []}\n'
        "Запись: очень тяжело, хотелось спать\n"
        '{"factors": [], "metrics": [{"name": "энергия", "value": 2}], "events": []}\n'
        "Запись: с утра поцапался с тёщей, весь день как выжатый лимон, ночью ворочался\n"
        '{"factors": [{"name": "ссора с тёщей", "value": 1}], '
        '"metrics": [{"name": "энергия", "value": 2}, {"name": "качество сна", "value": 4}], '
        '"events": []}\n'
        "\n"
        "Запись:\n"
    )

    def __init__(self, complete) -> None:
        """complete(prompt: str) -> str — любой вызов модели, возвращающий текст."""
        self._complete = complete

    def extract(self, text: str, day: date) -> DayRecord:
        record = DayRecord(day=day, raw_text=text)
        raw = self._complete(self.PROMPT + text)
        data = _parse_json(raw)
        for item in data.get("factors", []):
            name = str(item.get("name", "")).strip().lower()
            # «сон» - это то, что измеряют, а не то, что делают. Модель иногда
            # кладёт показатель в привычки; такие записи только мусорят список.
            if not name or _canonical_metric(name):
                continue
            record.add(Fact("factor", canonical_factor(name),
                            float(item.get("value", 1)), "diary"))
        lowered = text.lower()
        for item in data.get("metrics", []):
            name = _canonical_metric(str(item.get("name", "")).strip().lower())
            if not name:
                continue        # показатель не из нашего списка - в статистику не годится
            value = float(item.get("value", 0))
            # Модель любит дописать нули по всем показателям сразу. Ноль без
            # единого слова об этом в тексте - выдумка, а не наблюдение.
            # А вот ненулевую оценку принимаем: модель прочитала фразу целиком
            # и понимает «весело» или «выжат» лучше любого словаря.
            if value == 0 and not _mentioned(name, lowered):
                continue
            record.add(Fact("metric", name, value, "diary"))
        for name in data.get("events", []):
            record.add(Fact("event", str(name).strip().lower(), 1.0, "diary"))
        return record


