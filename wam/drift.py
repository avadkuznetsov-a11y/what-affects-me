"""
Длительные отклонения: показатель, который неделями держится не как обычно.

`today.py` сравнивает сегодняшний день с прежними, `insights.py` ищет связь
между привычкой и самочувствием. Между ними дыра: человек может месяц прожить
с энергией ниже своей нормы, и дневник об этом промолчит. Связи тут нет - есть
устойчивое отклонение, и заметить его, кроме программы, некому: изнутри такой
месяц выглядит как «что-то я устал», а не как ровная линия ниже обычной.

Норму считаем так же, как `wearables.own_norm` считает «готовность» кольца: это
средний уровень самого человека за месяц ДО отклонения, а не общая для всех
граница. У энергии, сна и настроения общей границы не существует вовсе - у
одного человека пятёрка обычный день, у другого провал.

Отклонением называем только то, что держится неделями подряд: плохая неделя
бывает у всех, четыре плохие недели подряд - это уже не погода и не понедельник.

Границы того, что мы про это говорим, жёсткие:

* никаких болезней, анализов, витаминов и лекарств. По дневнику отличить
  анемию от щитовидки, депрессии, апноэ и обычного недосыпа нельзя, и совет
  «сдайте железо» либо случайно угадает, либо уведёт человека не туда;
* никаких «вам следует» и «нужно» - только «вижу в ваших данных вот что»;
* про врача говорим одно: у человека на руках есть эти записи, и специалист
  посмотрит на них с той стороны, с которой мы не умеем. Это предложение
  отдать материал, а не назначение и не диагноз.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta

from .diary import Diary
from .schema import Timeline
from .wearables import own_norm

WEEK = 7

# Две недели - самый короткий срок, который вообще можно назвать длительным.
# Одна плохая неделя это командировка, простуда или отчётный период.
MIN_WEEKS = 2

# Неделя, про которую известно меньше трёх дней, в счёт не идёт: по одной
# записи нельзя сказать, какой была неделя.
MIN_DAYS_IN_WEEK = 3

# На сколько баллов неделя должна отойти от нормы. Балл десятибалльной шкалы -
# та же граница, что у `today.NOTABLE_GAP` и у факторов в `derive.OWN_NORM`:
# полбалла - шум, и на средних за неделю тем более.
DRIFT_GAP = 1.0

# Срок, с которого предлагаем показать записи специалисту. Месяц - это уже не
# полоса: столько человек и сам терпит, прежде чем куда-то пойти.
DOCTOR_WEEKS = 4

# Как часто про это вообще можно заговаривать. Отклонение никуда не денется за
# сутки, а фраза про него тяжёлая - повторять её каждый день значит превратить
# дневник в источник тревоги.
QUIET_DAYS = 3

# Как назвать отклонение словами. Шкала внутри программы одна: больше - лучше,
# поэтому «ниже нормы» у пульса покоя означает, что пульс ВЫШЕ обычного.
#
# Показателя нет в этой таблице - про него молчим. Запасная фраза вроде
# «сатурация ниже вашей обычной» человеком читается как медицинское
# утверждение, а мы его не делаем.
_WORDING: dict[str, tuple[str, str]] = {
    # показатель:      (держится ниже нормы,               держится выше нормы)
    "энергия":         ("Энергия ниже вашей обычной",
                        "Энергия выше вашей обычной"),
    "качество сна":    ("Спится хуже, чем вам обычно",
                        "Спится лучше, чем вам обычно"),
    "настроение":      ("Настроение ниже вашего обычного",
                        "Настроение выше вашего обычного"),
    "тревога":         ("Тревоги больше, чем у вас обычно",
                        "Тревоги меньше, чем у вас обычно"),
    "головная боль":   ("Голова болит чаще обычного",
                        "Голова болит реже обычного"),
    "стресс":          ("Напряжения больше, чем у вас обычно",
                        "Напряжения меньше, чем у вас обычно"),
    "активность":      ("Двигаетесь вы меньше обычного",
                        "Двигаетесь вы больше обычного"),
    "часов сна":       ("Спите вы меньше обычного",
                        "Спите вы больше обычного"),
    "пульс покоя":     ("Пульс покоя выше вашего обычного",
                        "Пульс покоя ниже вашего обычного"),
    "вариабельность пульса": ("Вариабельность пульса ниже вашей обычной",
                              "Вариабельность пульса выше вашей обычной"),
}

# Очевидные объяснения, которые человек назовёт первыми: «ну я же не высыпаюсь».
# Проверяем их по его же данным и говорим только про те, что НЕ подтвердились -
# именно этим наблюдение и ценно. Подтвердившееся объяснение не называем: если
# сон тоже просел, про сон он услышит отдельной строкой, как про своё отклонение.
_SUSPECTS: dict[str, tuple[str, ...]] = {
    "энергия":        ("качество сна", "часов сна", "активность"),
    "настроение":     ("качество сна", "активность"),
    "тревога":        ("качество сна",),
    "головная боль":  ("качество сна", "часов сна"),
    "качество сна":   ("активность",),
}

_RULED_OUT: dict[str, str] = {
    "качество сна": "сон тут ни при чём - он в норме",
    "часов сна":    "спите вы столько же, сколько обычно",
    "активность":   "двигаетесь вы не меньше обычного",
}

# Порядковое числительное для «четвёртую неделю подряд». Дальше двенадцати
# считаем обычным числом: «уже 14 недель подряд» звучит нормально, а
# «четырнадцатую неделю» - уже нет.
_ORDINAL = {2: "вторую", 3: "третью", 4: "четвёртую", 5: "пятую", 6: "шестую",
            7: "седьмую", 8: "восьмую", 9: "девятую", 10: "десятую",
            11: "одиннадцатую", 12: "двенадцатую"}


@dataclass(frozen=True)
class Drift:
    """Показатель, который держится не как обычно несколько недель подряд."""

    metric: str
    weeks: int
    worse: bool          # ниже нормы человека (по шкале «больше - лучше»)
    norm: float          # обычный уровень человека до отклонения
    level: float         # средний уровень за эти недели
    ruled_out: str = ""  # очевидное объяснение, которое по данным не подтвердилось


def find(timeline: Timeline, day: date) -> Drift | None:
    """
    Самое длительное отклонение на этот день. None - ничего такого нет.

    Показываем одно: два отклонения за раз человек читает как список диагнозов,
    хотя это одна и та же неделя, посчитанная с разных сторон.
    """
    found: list[Drift] = []
    for metric in sorted(timeline.metric_names()):
        if metric not in _WORDING:
            continue
        stretch = _stretch(timeline.series("metric", metric), day)
        if stretch is None:
            continue
        weeks, worse, norm, level = stretch
        found.append(Drift(metric, weeks, worse, norm, level))
    if not found:
        return None

    # Самое длинное; при равном сроке - то, что отошло от нормы дальше.
    best = max(found, key=lambda d: (d.weeks, abs(d.norm - d.level)))
    return Drift(best.metric, best.weeks, best.worse, best.norm, best.level,
                 _ruled_out(timeline, best, day))


def phrase(drift: Drift) -> str:
    """Как сказать про это человеку."""
    said = f"{_WORDING[drift.metric][0 if drift.worse else 1]} {_weeks_said(drift.weeks)}"
    if not drift.worse:
        # Про хорошее тоже говорим: дневник, который открывает рот только когда
        # плохо, человек закрывает через неделю.
        return f"{said}. Это тоже стоит заметить - обычно замечают только плохое."

    if drift.ruled_out:
        said += f", и {drift.ruled_out}"
    said += (". Это не диагноз: я вижу только цифры в ваших записях "
             "и не знаю, что за ними стоит.")
    if drift.weeks >= DOCTOR_WEEKS:
        how_long = "уже месяц" if drift.weeks == DOCTOR_WEEKS else "больше месяца"
        said += (f" Держится это {how_long} - есть смысл показать эти записи врачу: "
                 f"он посмотрит на них с той стороны, с которой я не умею.")
    return said


def notice(diary: Diary, day: date) -> str:
    """
    Что сказать про длительное отклонение прямо сейчас; пусто - молчим.

    Здесь же и редкость: фраза тяжёлая, и человек должен слышать её раз в
    несколько дней, а не в ответ на каждую запись. Одно и то же слово в слово
    не повторяем вовсе - для этого в дневнике есть `observed`.

    День, в который сказали, живёт только в памяти процесса: после перезапуска
    программы отклонение назовётся ещё раз. Это лучше обратного - тащить на
    диск лишнее про здоровье человека ради одной сэкономленной фразы.
    """
    if diary.drift_said is not None and (day - diary.drift_said).days < QUIET_DAYS:
        return ""
    drift = find(diary.timeline, day)
    if drift is None:
        return ""
    line = phrase(drift)
    if line in diary.observed:
        return ""
    diary.observed.add(line)
    diary.drift_said = day
    return line


def _stretch(series: dict[date, float],
             day: date) -> tuple[int, bool, float, float] | None:
    """
    Сколько недель подряд показатель держится не как обычно: (недели, ниже ли
    нормы, норма, средний уровень). None - отклонения нет.

    Каждый срок проверяем целиком и берём самый длинный, который сошёлся: все
    недели внутри него должны отойти от нормы в одну и ту же сторону. Норму
    считаем от дня, в который срок начинается, - у длинного отклонения она
    берётся из времён ДО него, и в этом весь смысл.

    Расти сроком, пока сходится, и останавливаться на первой несошедшейся
    неделе нельзя, хотя это и выглядит естественнее: на коротком сроке норма
    посчитана по дням, которые в отклонение уже входят, и месяц ниже обычного
    не находился вовсе - он сам себе становился нормой. Оборванный срок такая
    проверка всё равно отсекает: неделя, вернувшаяся к своему уровню, не пройдёт
    ни при какой норме, а с ней не пройдёт и любой срок длиннее.
    """
    best: tuple[int, bool, float, float] | None = None
    weeks = MIN_WEEKS
    while True:
        first = day - timedelta(days=WEEK * weeks - 1)
        # Нормы нет - значит, до этого срока своих дней у человека меньше
        # недели. Дальше срок только длиннее, а дней до него только меньше:
        # смотреть больше не на что.
        norm = own_norm(series, first)
        if norm is None:
            break
        means = _weekly_means(series, day, weeks)
        if means is None:
            break               # в какой-то из недель записей почти нет
        if all(mean <= norm - DRIFT_GAP for mean in means):
            worse = True
        elif all(mean >= norm + DRIFT_GAP for mean in means):
            worse = False
        else:
            weeks += 1
            continue
        values = [value for when, value in series.items() if first <= when <= day]
        best = (weeks, worse, norm, sum(values) / len(values))
        weeks += 1
    return best


def _weekly_means(series: dict[date, float], day: date,
                  weeks: int) -> list[float] | None:
    """
    Средние по неделям, считая назад от дня. None - хотя бы в одной неделе
    записей меньше трёх: про такую неделю сказать нечего, и делать вид, что она
    подтверждает срок, нельзя.
    """
    means = []
    for number in range(weeks):
        last = day - timedelta(days=WEEK * number)
        first = last - timedelta(days=WEEK - 1)
        values = [value for when, value in series.items() if first <= when <= last]
        if len(values) < MIN_DAYS_IN_WEEK:
            return None
        means.append(sum(values) / len(values))
    return means


def _ruled_out(timeline: Timeline, drift: Drift, day: date) -> str:
    """
    Очевидное объяснение, которое по данным не подтвердилось.

    «В норме» говорим только про то, что действительно измерено все эти недели
    и действительно держится около своей нормы. Про хорошее отклонение ничего
    не отсекаем: там нечего объяснять.
    """
    if not drift.worse:
        return ""
    first = day - timedelta(days=WEEK * drift.weeks - 1)
    for name in _SUSPECTS.get(drift.metric, ()):
        series = timeline.series("metric", name)
        norm = own_norm(series, first)
        if norm is None:
            continue
        values = [value for when, value in series.items() if first <= when <= day]
        if len(values) < MIN_DAYS_IN_WEEK * drift.weeks:
            continue        # мерили через раз - «он в норме» на этом не построишь
        if abs(sum(values) / len(values) - norm) < DRIFT_GAP:
            return _RULED_OUT[name]
    return ""


def _weeks_said(count: int) -> str:
    """«четвёртую неделю подряд» или «уже 14 недель подряд»."""
    word = _ORDINAL.get(count)
    if word:
        return f"{word} неделю подряд"
    return f"уже {count} {_weeks_word(count)} подряд"


def _weeks_word(count: int) -> str:
    if 11 <= count % 100 <= 14:
        return "недель"
    last = count % 10
    if last == 1:
        return "неделю"
    if 2 <= last <= 4:
        return "недели"
    return "недель"
